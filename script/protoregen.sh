#!/usr/bin/env bash
# Regenerate code from .bgn schemas via the brgen local api server.
#
# Most schemas generate a single Go file (lang go3, out = <bgn>.go). Schemas
# listed in MULTI_TARGET below instead generate an explicit set of
# (lang, outpath) pairs — used for cross-language ABIs like the edge
# host<->wasm ABI (Go host + Rust guest from one schema).
#
# - First run downloads and installs the brgen server-kit into a user
#   cache (~/.cache/brgen-kit), about 20 MB tarball + 330 npm packages.
# - Subsequent runs reuse the cache; only the api server start (~5 s)
#   and the codegen round-trip (~1 s) are paid per invocation.
# - The server runs on port 8181 by default (override BRGEN_PORT env).
#
# Usage:
#   script/protoregen.sh                # regenerate the default set
#   script/protoregen.sh path/to/x.bgn  # regenerate a single file (out path inferred)
#   script/protoregen.sh --all          # regenerate every .bgn under the repo
#   script/protoregen.sh --refresh ...   # wipe the cache and re-download the
#                                         latest server-kit before regenerating
#                                         (also: BRGEN_REFRESH=1). Use this when
#                                         brgen itself has been updated upstream.
#
# Output language is fixed to go3 (= ebm2go, matching the existing
# `// Code generated by ebm2go ...` headers).
set -euo pipefail

BRGEN_CACHE="${BRGEN_CACHE:-${HOME}/.cache/brgen-kit}"
BRGEN_PORT="${BRGEN_PORT:-8181}"
BRGEN_URL="${BRGEN_URL:-https://on-keyday.github.io/brgen/server-kit.tar.gz}"
BRGEN_LANG="${BRGEN_LANG:-go3}"
BRGEN_REFRESH="${BRGEN_REFRESH:-0}"

# Default set: schemas touched during active development. Stable schemas
# (protobuf/wire/, rpc/wire/, trsf/proxy/wire/, l4lb/l4lbdrv/wire/,
# ca/storage/index/, popcache/*) are passed explicitly or via --all.
DEFAULT_BGNS=(
    "remoteexec/wire/preamble.bgn"
)

# Schemas that generate to MORE than the single inferred go3/.go target, or to a
# non-go language. Value is a space-separated list of targets; these REPLACE the
# default inference for that .bgn. Each target is:
#     lang:outpath[|opt=val,opt=val]
# where the optional "|opt=val,..." tail sets generator options (see
# /api/languages for each lang's option keys). Checkbox options take "true".
# Used for cross-language ABIs (e.g. the edge host<->wasm ABI: Go host side +
# Rust guest side, both from one schema so the wire format stays in lockstep by
# construction). The Rust guest uses zero-copy (borrowed structs with
# lifetimes), matching how the hand-written edge_app consumer is written.
declare -A MULTI_TARGET=(
    ["popcache/edge/request_info.bgn"]="go3:popcache/edge/request_info.go rust3:edge_app/api/src/api/edge.rs|zero-copy=true"
)

# --- arg parsing ----------------------------------------------------------

# Strip flags that are not .bgn targets first, so --refresh composes with
# --all / explicit targets in any position.
ARGS=()
for a in "$@"; do
    case "$a" in
        --refresh) BRGEN_REFRESH=1 ;;
        *) ARGS+=("$a") ;;
    esac
done

TARGETS=()
if [ ${#ARGS[@]} -eq 0 ]; then
    TARGETS=("${DEFAULT_BGNS[@]}")
elif [ "${ARGS[0]}" = "--all" ]; then
    while IFS= read -r f; do
        TARGETS+=("$f")
    done < <(find . -name '*.bgn' \
        -not -path '*/node_modules/*' \
        -not -path '*/.harness-worktrees/*' \
        -not -path '*/.cache/*' \
        | sed 's|^\./||')
else
    TARGETS=("${ARGS[@]}")
fi

if [ ${#TARGETS[@]} -eq 0 ]; then
    echo "no .bgn targets to regenerate" >&2
    exit 1
fi

# --- setup cache ----------------------------------------------------------

if [ "${BRGEN_REFRESH}" = "1" ] && [ -e "${BRGEN_CACHE}" ]; then
    echo "==> --refresh: wiping cache at ${BRGEN_CACHE} to pull the latest server-kit..."
    rm -rf "${BRGEN_CACHE}"
fi

if [ ! -f "${BRGEN_CACHE}/.installed" ]; then
    echo "==> Setting up brgen server-kit cache at ${BRGEN_CACHE}..."
    mkdir -p "${BRGEN_CACHE}"
    curl -fsSL "${BRGEN_URL}" | tar xz -C "${BRGEN_CACHE}"
    (cd "${BRGEN_CACHE}/web/dev" && npm install)
    touch "${BRGEN_CACHE}/.installed"
fi

# --- start api server -----------------------------------------------------

# Pre-flight: if the port is already taken, a stale server from an earlier run
# would answer our readiness probe and silently serve OLD generators (its code
# is held in memory, so even a cache --refresh would not reach it). Abort loudly
# rather than talk to it. Set BRGEN_PORT to a free port to work around a genuine
# collision with an unrelated service.
if (exec 3<>"/dev/tcp/localhost/${BRGEN_PORT}") 2>/dev/null; then
    exec 3>&- 3<&-
    echo "port ${BRGEN_PORT} is already in use — a stale brgen server would serve" >&2
    echo "old generators. Kill it (e.g. 'fuser -k ${BRGEN_PORT}/tcp') or set" >&2
    echo "BRGEN_PORT to a free port, then re-run." >&2
    exit 1
fi

echo "==> Starting brgen api server on port ${BRGEN_PORT}..."
LOG_FILE="$(mktemp)"
# Run in its own process group (setsid) so cleanup can kill the whole tree.
# 'npm run serve' forks a node child that is the actual listener; killing only
# the npm parent orphans that child and leaves it holding the port.
setsid bash -c "cd '${BRGEN_CACHE}/web/dev' && PORT='${BRGEN_PORT}' exec npm run serve" \
    >"${LOG_FILE}" 2>&1 &
SERVER_PID=$!

cleanup() {
    # Negative PID → signal the whole process group (setsid made SERVER_PID its
    # leader), so the node child dies with the npm parent.
    kill -- -"${SERVER_PID}" 2>/dev/null || kill "${SERVER_PID}" 2>/dev/null || true
    wait "${SERVER_PID}" 2>/dev/null || true
    rm -f "${LOG_FILE}"
}
trap cleanup EXIT

# Wait for /api/languages to respond (server is ready when ebmgen worker is up).
for _ in $(seq 1 30); do
    if curl -fsS "http://localhost:${BRGEN_PORT}/api/languages" >/dev/null 2>&1; then
        break
    fi
    sleep 1
done
if ! curl -fsS "http://localhost:${BRGEN_PORT}/api/languages" >/dev/null 2>&1; then
    echo "brgen api server did not become ready within 30 s" >&2
    cat "${LOG_FILE}" >&2 || true
    exit 1
fi

# --- regen each target ----------------------------------------------------

REQ_FILE="$(mktemp)"
RESP_FILE="$(mktemp)"
trap 'cleanup; rm -f "${REQ_FILE}" "${RESP_FILE}"' EXIT

# generate_one <bgn> <lang> <out> [opts]: round-trip one schema through the api
# server and write the result to <out>, formatting per output language.
# <opts> is an optional "key=val,key=val" string of generator options; a bare
# "key" (no "=") means the checkbox option "key=true".
generate_one() {
    local bgn="$1" lang="$2" out="$3" opts="${4:-}"
    echo "==> Regenerating ${out} (lang=${lang}${opts:+, opts=${opts}})..."
    python3 - "${bgn}" "${lang}" "${opts}" >"${REQ_FILE}" <<'PY'
import json, sys
src = open(sys.argv[1]).read()
req = {"source": src, "lang": sys.argv[2]}
opts = sys.argv[3] if len(sys.argv) > 3 else ""
if opts:
    o = {}
    for kv in opts.split(","):
        if not kv:
            continue
        if "=" in kv:
            k, v = kv.split("=", 1)
            if v in ("true", "false"):
                v = (v == "true")
            o[k] = v
        else:
            o[kv] = True
    req["options"] = o
print(json.dumps(req))
PY
    curl -fsS -X POST \
        -H "Content-Type: application/json" \
        --data @"${REQ_FILE}" \
        "http://localhost:${BRGEN_PORT}/api/generate" \
        -o "${RESP_FILE}"
    python3 - "${RESP_FILE}" "${out}" <<'PY'
import json, sys
r = json.load(open(sys.argv[1]))
if r.get("isError"):
    print("GENERATION ERROR:")
    print(r.get("code", "")[:4000])
    raise SystemExit(1)
open(sys.argv[2], "w").write(r["code"])
PY
    case "${out}" in
        *.go) gofmt -w "${out}" ;;
        # Leave generator-native formatting for other languages (matches how the
        # committed output looks; rustfmt would add unrelated churn).
    esac
}

for bgn in "${TARGETS[@]}"; do
    if [ ! -f "${bgn}" ]; then
        echo "no such .bgn: ${bgn}" >&2
        exit 1
    fi
    if [ -n "${MULTI_TARGET[${bgn}]:-}" ]; then
        for target in ${MULTI_TARGET[${bgn}]}; do
            # target = lang:outpath[|opt=val,...]
            langout="${target%%|*}"
            opts=""
            [ "${target}" != "${langout}" ] && opts="${target#*|}"
            generate_one "${bgn}" "${langout%%:*}" "${langout#*:}" "${opts}"
        done
    else
        generate_one "${bgn}" "${BRGEN_LANG}" "${bgn%.bgn}.go"
    fi
done

echo "==> Done. Regenerated: ${TARGETS[*]}"
