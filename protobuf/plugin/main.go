const (
	UnaryRPC = iota
	ClientStreamingRPC
	ServerStreamingRPC
	BidirectionalStreamingRPC
)

type rpcSignature struct {
	method        *protogen.Method
	rpcType       int
	clientInType  []string
	clientOutType []string
	serverInType  []string
	serverOutType []string

	clientStubReturn string
}

func processService(g *protogen.GeneratedFile, service *protogen.Service) {
	// 1. インターフェース定義

	streamTypes := map[string]string{}
	order := make([]string, 0)

	signatures := make([]*rpcSignature, 0)

	serviceName := service.Desc.FullName()

	for _, method := range service.Methods {
		// 入力・出力の型を取得
		rpcType := UnaryRPC
		if method.Desc.IsStreamingClient() && method.Desc.IsStreamingServer() {
			rpcType = BidirectionalStreamingRPC
		} else if method.Desc.IsStreamingClient() {
			rpcType = ClientStreamingRPC
		} else if method.Desc.IsStreamingServer() {
			rpcType = ServerStreamingRPC
		}

		inType := mayWellknownTypeIdent(g, method.Input.GoIdent)
		outType := mayWellknownTypeIdent(g, method.Output.GoIdent)
		// unary -> func(ctx context.Context, req *In) (*Out, error)
		// client streaming ->
		// on server, func(ctx context.Context,in *ClientStream) (*Out, error)
		//           *ClientStream -> Recv() (*In, error)
		// on client, func(ctx context.Context) (*ClientStream, error)
		//           *ClientStream -> Send(*In) error, CloseAndRecv() (*Out, error)
		// server streaming ->
		// on server, func(ctx context.Context, req *In,out *ServerStream) error
		//            *ServerStream -> Send(*Out) error
		// on client, func(ctx context.Context, req *In) error
		//            *ServerStream -> Recv() (*Out, error)
		// bidi streaming ->
		// on server, func(ctx context.Context, stream *BidiStream) error
		//            *BidiStream -> Send(*Out) error, Recv() (*In, error)
		// on client, func(ctx context.Context) (*BidiStream, error)
		//            *BidiStream -> Send(*In) error, Recv() (*Out, error)
		sig := &rpcSignature{
			method:  method,
			rpcType: rpcType,
		}
		methodName := method.Desc.Name()
		ctxIdent := g.QualifiedGoIdent(contextPkg.Ident("Context"))
		switch rpcType {
		case UnaryRPC:
			// Unary は標準 gRPC 同様 ctx を第一引数に置く。Bidi/ClientStreaming は
			// I/O をすべて stream object に委ねるので引数には ctx を含めない。
			// ServerStreaming だけは生成時に最初の request を Send するため
			// (wire.NewReceiveStream の初期 Send)、ctx を第一引数に取る。
			sig.clientInType = []string{ctxIdent, "*" + inType}
			sig.clientOutType = []string{"*" + outType, "error"}
			sig.serverInType = []string{ctxIdent, "*" + inType}
			sig.serverOutType = []string{"*" + outType, "error"}
			sig.clientStubReturn = fmt.Sprintf("wire.NewCall[%s, %s](arg0, %q,%q, c.stream,arg1)", inType, outType, serviceName, methodName)
		case ClientStreamingRPC:
			clientStreamName := service.GoName + method.GoName + "ClientStream"
			streamTypes[clientStreamName] = fmt.Sprintf("wire.ClientStream[%s, %s,*%s,*%s]", inType, outType, inType, outType)
			order = append(order, clientStreamName)
			serverStreamName := service.GoName + method.GoName + "ServerStream"
			streamTypes[serverStreamName] = fmt.Sprintf("wire.ServerStream[%s, %s,*%s,*%s]", inType, outType, inType, outType)
			order = append(order, serverStreamName)

			sig.clientInType = []string{}
			sig.clientOutType = []string{"*" + clientStreamName, "error"}
			sig.serverInType = []string{"*" + serverStreamName}
			sig.serverOutType = []string{"error"}
			sig.clientStubReturn = fmt.Sprintf("wire.NewClientStream[%s,%s](%q,%q, c.stream)", inType, outType, serviceName, methodName)
		case ServerStreamingRPC:
			clientStreamName := service.GoName + method.GoName + "ClientStream"
			streamTypes[clientStreamName] = fmt.Sprintf("wire.ReceiveStream[%s, %s, *%s, *%s]", inType, outType, inType, outType)
			order = append(order, clientStreamName)
			serverStreamName := service.GoName + method.GoName + "ServerStream"
			// server 側は client の SendStream (= 新規 stream を開き request frame を
			// 書く) ではなく ServerSendStream (dispatcher 注入の send closure 経由で
			// response frame を書く) を使う。
			streamTypes[serverStreamName] = fmt.Sprintf("wire.ServerSendStream[%s,*%s]", outType, outType)
			order = append(order, serverStreamName)

			sig.clientInType = []string{ctxIdent, "*" + inType}
			sig.clientOutType = []string{"*" + clientStreamName, "error"}
			// server handler は unary と同じく ctx を第一引数に取り (ABAC/config 用に
			// rpc.AgentContextFromContext で AgentContext を取り出せる)、request と
			// ServerSendStream を受ける。
			sig.serverInType = []string{ctxIdent, "*" + inType, "*" + serverStreamName}
			sig.serverOutType = []string{"error"}
			sig.clientStubReturn = fmt.Sprintf("wire.NewReceiveStream[%s,%s](arg0,%q,%q, c.stream,arg1)", inType, outType, serviceName, methodName)
		case BidirectionalStreamingRPC:
			clientStreamName := service.GoName + method.GoName + "ClientStream"
			streamTypes[clientStreamName] = fmt.Sprintf("wire.Stream[%s, %s,*%s,*%s]", inType, outType, inType, outType)
			order = append(order, clientStreamName)
			serverStreamName := service.GoName + method.GoName + "ServerStream"
			streamTypes[serverStreamName] = fmt.Sprintf("wire.Stream[%s, %s,*%s,*%s]", outType, inType, outType, inType)
			order = append(order, serverStreamName)

			sig.clientInType = []string{}
			sig.clientOutType = []string{"*" + clientStreamName, "error"}
			sig.serverInType = []string{"*" + serverStreamName}
			sig.serverOutType = []string{"error"}
			sig.clientStubReturn = fmt.Sprintf("wire.NewStream[%s, %s](%q,%q, c.stream)", inType, outType, serviceName, methodName)
		}
		signatures = append(signatures, sig)
	}
	inSigJoin := func(types []string) string {
		if len(types) == 0 {
			return ""
		}
		buf := make([]string, len(types))
		for i, t := range types {
			buf[i] = "arg" + strconv.Itoa(i) + " " + t
		}
		return strings.Join(buf, ", ")
	}
	g.P("type ", service.GoName, "Server interface {")
	for _, sig := range signatures {
		g.P("  ", sig.method.GoName, "(", strings.Join(sig.serverInType, ", "), ") (", strings.Join(sig.serverOutType, ", "), ")")
	}
	g.P("}")
	g.P()

	for _, streamType := range order {
		g.P("type ", streamType, " = ", streamTypes[streamType])
	}

	// 2. サーバースタブ生成
	// ここでは簡単のため、すべてのメソッドを未実装のスタブとして生成
	g.P("type Unimplemented", service.GoName, "Server struct {")
	g.P("}")
	g.P()

	for _, sig := range signatures {
		g.P("func (s *Unimplemented", service.GoName, "Server) ", sig.method.GoName, "(", strings.Join(sig.serverInType, ", "), ") (", strings.Join(sig.serverOutType, ", "), ") {")
		sigReturns := make([]any, 0, len(sig.serverOutType)+1)
		sigReturns = append(sigReturns, "return ")
		for i, out := range sig.serverOutType {
			if i > 0 {
				sigReturns = append(sigReturns, ", ")
			}
			if out == "error" {
				sigReturns = append(sigReturns, errorsPkg.Ident("New"), "(\"method ", sig.method.Desc.FullName(), " not implemented\")")
			} else {
				sigReturns = append(sigReturns, "nil")
			}
		}
		g.P(sigReturns...)
		g.P("}")
		g.P()
	}

	// クライアントシグネチャ

	g.P("type ", service.GoName, "Client interface {")
	for _, sig := range signatures {
		g.P("  ", sig.method.GoName, "(", strings.Join(sig.clientInType, ", "), ") (", strings.Join(sig.clientOutType, ", "), ")")
	}
	g.P("}")
	g.P()

	// 3. クライアントスタブ生成
	// client stub は "wire." を literal で吐く (clientStubReturn / 下記 struct)
	// ため、message を持たない service-only proto では protobuf/wire import が
	// 自動登録されない。ここで明示的に登録しておく (返り値の qualified 名は
	// package 名 "wire" になり literal と一致する)。
	g.QualifiedGoIdent(wirePkg.Ident("StreamSource"))
	g.P("type Default", service.GoName, "Client struct {")
	g.P("   stream *wire.StreamSource")
	g.P("}")
	g.P()

	for _, sig := range signatures {
		g.P("func (c *Default", service.GoName, "Client) ", sig.method.GoName, "(", inSigJoin(sig.clientInType), ") (", strings.Join(sig.clientOutType, ", "), ") {")
		g.P("  return ", sig.clientStubReturn)
		g.P("}")
		g.P()
	}

	g.P("func New", service.GoName, "Client(stream *wire.StreamSource) ", service.GoName, "Client {")
	g.P("  return &Default", service.GoName, "Client{stream: stream}")
	g.P("}")
	g.P()

	// 4. サーバー登録ヘルパー (Unary + ServerStreaming)。
	// ksdk 内部 RPC dispatcher (rpc.Registry) に各メソッドを登録する。Unary は
	// bytes-in/bytes-out の MethodHandler、ServerStreaming は reqBody + send closure
	// を取る StreamMethodHandler として登録する。ClientStreaming / Bidi の server
	// 登録はまだ未対応 (dispatcher 側が server-streaming のみ対応)。
	registryIdent := g.QualifiedGoIdent(rpcPkg.Ident("Registry"))
	//agentCtxIdent := g.QualifiedGoIdent(agentPkg.Ident("AgentContext"))
	//withAgentCtxIdent := g.QualifiedGoIdent(rpcPkg.Ident("WithAgentContext"))
	g.P("func Register", service.GoName, "Server(reg ", registryIdent, ", impl ", service.GoName, "Server) {")
	for _, sig := range signatures {
		methodName := sig.method.Desc.Name()
		switch sig.rpcType {
		case UnaryRPC:
			inType := mayWellknownTypeIdent(g, sig.method.Input.GoIdent)
			g.P("  reg.RegisterMethod(", strconv.Quote(string(serviceName)), ", ", strconv.Quote(string(methodName)), ",")
			g.P("    func(ctx ", contextPkg.Ident("Context"), ", body []byte) ([]byte, error) {")
			g.P("      req := &", inType, "{}")
			g.P("      if err := req.Decode(body); err != nil {")
			g.P("        return nil, err")
			g.P("      }")
			// impl 側が *agent.AgentContext を必要とする可能性があるため
			// rpc.WithAgentContext で ctx に詰めてから渡す。
			// impl 側は rpc.AgentContextFromContext で取り出す。
			g.P("      resp, err := impl.", sig.method.GoName, "(ctx, req)")
			g.P("      if err != nil {")
			g.P("        return nil, err")
			g.P("      }")
			g.P("      return resp.Append(nil)")
			g.P("    })")
		case ServerStreamingRPC:
			inType := mayWellknownTypeIdent(g, sig.method.Input.GoIdent)
			outType := mayWellknownTypeIdent(g, sig.method.Output.GoIdent)
			g.P("  reg.RegisterStreamMethod(", strconv.Quote(string(serviceName)), ", ", strconv.Quote(string(methodName)), ",")
			g.P("    func(ctx ", contextPkg.Ident("Context"), ", body []byte, send func([]byte) error) error {")
			g.P("      req := &", inType, "{}")
			g.P("      if err := req.Decode(body); err != nil {")
			g.P("        return err")
			g.P("      }")
			// ServerSendStream は dispatcher の send closure をラップし、impl が
			// Send(*Out) するたび RPCResponseMessage{Ok} を書き出す。終端 (stream_end)
			// は impl が return した時点で dispatcher が付ける。
			g.P("      stream := wire.NewServerSendStream[", outType, ", *", outType, "](send)")
			g.P("      return impl.", sig.method.GoName, "(ctx, req, stream)")
			g.P("    })")
		default:
			// ClientStreaming / Bidi: server 登録未対応。
			continue
		}
	}
	g.P("}")

}

func isWellKnownType(path string) bool {
	return strings.HasPrefix(path, "google/protobuf/")
}

func mayWellknownTypeIdent(g *protogen.GeneratedFile, ident protogen.GoIdent) string {
	if strings.HasPrefix(string(ident.GoImportPath), "google.golang.org/protobuf/types/known/") {
		return g.QualifiedGoIdent(protogen.GoIdent{
			GoImportPath: "github.com/on-keyday/kscale/protobuf/wkt",
			GoName:       ident.GoName,
		})
	}
	return g.QualifiedGoIdent(ident)
}
