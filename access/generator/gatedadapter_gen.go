// GatedAdapterFile is one generated ABAC-gate adapter Go file: a repo-relative
// output path plus its full source. GenerateGatedAdapters returns one per
// rpc_service resource; cmd/gen (mode "gated_adapters") writes them to disk.
type GatedAdapterFile struct {
	Path    string
	Content string
}

// gatedAdapterUseImports maps a `response: { use: X }` Go type's package prefix
// to the import path the gate adapter needs to name it. `pb` is always imported,
// so it is intentionally absent. Extend when a resource opts into a `use:`
// response from a new package.
var gatedAdapterUseImports = map[string]string{
	"wkt":    "github.com/on-keyday/kscale/protobuf/wkt",
	"pbstat": "github.com/on-keyday/kscale/protobuf/proto/stat",
}

// GenerateGatedAdapters emits, for every resource with rpc_service: true, the
// generated ABAC gate {Resource}Gated. It is a decorator over the full
// pb.{Resource}ServiceServer interface: it holds the real business as an
// `Inner` of that interface type and, for every action, runs the access gate
// (caller recovered from the peer, $env.args built from the request DTO, plus
// $env.authority) before delegating to Inner. The business implementation stays
// hand-written ({Resource}Handlers, embedding pb.Unimplemented{Resource}ServiceServer
// so partially-implemented services still satisfy the interface); only the gate
// is mechanical (kscale charter M4 — replaces the hand-written CaManagementGated).
func GenerateGatedAdapters(input *Input) []GatedAdapterFile {
	var files []GatedAdapterFile
	for _, r := range input.Definition.Resources {
		if !r.generatesGate() {
			continue
		}
		var buf bytes.Buffer
		emitGatedAdapter(&Writer{W: &buf}, &r)
		files = append(files, GatedAdapterFile{
			Path:    filepath.Join("service", r.Name+"_gated_gen.go"),
			Content: buf.String(),
		})
	}
	return files
}

func emitGatedAdapter(w *Writer, r *ResourceTemplate) {
	svc := toCamelCase(r.Name) // CaManagement
	gated := svc + "Gated"     // CaManagementGated

	// Resolve the extra imports the `use:` response types and no-response actions
	// (google.protobuf.Empty == wkt.Empty) pull in, keyed by their use-type
	// package prefix (the import alias). Streaming actions add nothing (they name
	// the pb.<Svc>Service<Action>ServerStream alias in the always-imported pb).
	extraUseImports := map[string]string{}
	for _, a := range r.rpcActions() {
		if a.isStreamingResponse() {
			continue
		}
		if a.Response == nil {
			extraUseImports["wkt"] = gatedAdapterUseImports["wkt"]
			continue
		}
		if a.Response.Use != nil {
			prefix, _, ok := strings.Cut(*a.Response.Use, ".")
			if !ok {
				panic(fmt.Errorf("emitGatedAdapter: resource %q action %q use type %q is not package-qualified", r.Name, a.Name, *a.Response.Use))
			}
			if prefix == "pb" {
				continue // pb is always imported
			}
			imp, known := gatedAdapterUseImports[prefix]
			if !known {
				panic(fmt.Errorf("emitGatedAdapter: resource %q action %q use type %q has no import mapping (add it to gatedAdapterUseImports)", r.Name, a.Name, *a.Response.Use))
			}
			extraUseImports[prefix] = imp
		}
	}
	aliases := make([]string, 0, len(extraUseImports))
	for alias := range extraUseImports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)

	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package service\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "fmt")
		w.Printf("\n")
		w.Printf("%q\n", "github.com/on-keyday/kscale/access")
		w.Printf("%q\n", "github.com/on-keyday/kscale/access/audit")
		w.Printf("%q\n", "github.com/on-keyday/kscale/peer")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("pbaccess %q\n", "github.com/on-keyday/kscale/protobuf/proto/access")
		for _, alias := range aliases {
			path := extraUseImports[alias]
			if alias == filepath.Base(path) {
				w.Printf("%q\n", path)
			} else {
				w.Printf("%s %q\n", alias, path)
			}
		}
	})
	w.Printf(")\n\n")

	w.Printf("// %s is the generated ABAC gate for %sService. It implements the full\n", gated, svc)
	w.Printf("// pb.%sServiceServer surface as a decorator over Inner (the hand-written\n", svc)
	w.Printf("// business): every method authorizes the caller against the resource policy\n")
	w.Printf("// (caller from the peer, $env.args from the request, $env.authority from the\n")
	w.Printf("// root) and then delegates to Inner. Registering this — never Inner directly —\n")
	w.Printf("// is what keeps the gate on every action.\n")
	w.Printf("type %s struct {\n", gated)
	w.Indented(func(w *Writer) {
		w.Printf("Inner      pb.%sServiceServer\n", svc)
		w.Printf("Controller access.AccessController\n")
		w.Printf("Resource   access.Resource\n")
		w.Printf("Root       access.RootAuthority // supplies $env.authority\n")
		w.Printf("Audit      audit.Audit\n")
	})
	w.Printf("}\n\n")
	w.Printf("var _ pb.%sServiceServer = (*%s)(nil)\n\n", svc, gated)

	w.Printf("// authorize runs the ABAC gate for action using the caller carried by the\n")
	w.Printf("// peer and args exposed as $env.args.\n")
	w.Printf("func (s *%s) authorize(ctx context.Context, action string, args []access.Attribute) error {\n", gated)
	w.Indented(func(w *Writer) {
		w.Printf("p := peer.GetPeer(ctx)\n")
		w.Printf("if p == nil || p.Policy() == nil || p.Policy().User == nil {\n")
		w.Indented(func(w *Writer) {
			w.Printf("return fmt.Errorf(%q)\n", "permission denied: unauthenticated caller")
		})
		w.Printf("}\n")
		w.Printf("envAttrs := []access.Attribute{access.NewAuthorityAttributeMapper(s.Root)}\n")
		w.Printf("if len(args) > 0 {\n")
		w.Indented(func(w *Writer) {
			w.Printf("envAttrs = append(envAttrs, access.NewAttributeManager(%q, args))\n", "args")
		})
		w.Printf("}\n")
		w.Printf("policyCtx := p.Policy().\n")
		w.Indented(func(w *Writer) {
			w.Printf("CollectResource(s.Resource).\n")
			w.Printf("CollectEnvironment(access.NewEnvironment(envAttrs)).\n")
			w.Printf("CollectAction(access.NewAction(action, nil)).\n")
			w.Printf("Build(ctx, s.Audit)\n")
		})
		w.Printf("if err := s.Controller.CanAccess(policyCtx); err != nil {\n")
		w.Indented(func(w *Writer) {
			w.Printf("return fmt.Errorf(%q, err)\n", "permission denied: %w")
		})
		w.Printf("}\n")
		w.Printf("return nil\n")
	})
	w.Printf("}\n\n")

	for _, a := range r.rpcActions() {
		emitGatedMethod(w, svc, gated, &a)
	}
}

// emitGatedArgs writes the []access.Attribute literal (or `nil`) that exposes the
// action's request fields as $env.args, mirroring the request DTO field names.
func gatedArgsExpr(a *Action) string {
	var parts []string
	for i := range a.Args {
		arg := &a.Args[i]
		if arg.Sensitive {
			// Secret-bearing: never expose as a policy attribute (keeps it out of
			// policy evaluation and the audit log).
			continue
		}
		if !isAttributable(arg.Type) {
			// Structured / non-scalar fields (e.g. []*pb.PortInfo) cannot be a
			// policy attribute; they are simply not exposed as $env.args.
			continue
		}
		parts = append(parts, fmt.Sprintf("access.NewAttribute(%q, %s)", arg.Name, attrValueExpr(arg)))
	}
	if len(parts) == 0 {
		return "nil"
	}
	return "[]access.Attribute{" + strings.Join(parts, ", ") + "}"
}

// isAttributable reports whether an arg's DTO field can be a policy attribute —
// i.e. its Go type is one access/policy.CheckAttributeType accepts (after the
// uint widening in attrValueExpr). Structured fields and bool are excluded.
func isAttributable(argType string) bool {
	switch argType {
	case "string", "uint32", "uint64", "time.Duration", "time.Time", "[]string",
		"netip.Addr", "objproto.ConnectionID", "*objproto.ConnectionID":
		return true
	}
	return false
}

// attrValueExpr is the Go expression for an arg's $env.args attribute value. The
// access policy attribute system (access/policy.CheckAttributeType) accepts a
// fixed set of types — string/int64/float64/time.Duration/time.Time/[]string/
// netip.Addr — so unsigned integer DTO fields are widened to int64 to avoid a
// runtime "unknown attribute type" panic.
func attrValueExpr(arg *ActionArg) string {
	field := "req." + toCamelCase(arg.Name)
	switch arg.Type {
	case "uint32", "uint64":
		return "int64(" + field + ")"
	default:
		return field
	}
}

func emitGatedMethod(w *Writer, svc, gated string, a *Action) {
	method := toCamelCase(a.Name) // CreateUserHierarchyAuthority
	reqProto := fmt.Sprintf("pbaccess.Resource%sAction%sArgsDTO", svc, method)
	args := gatedArgsExpr(a)

	if a.isStreamingResponse() {
		streamType := fmt.Sprintf("pb.%sService%sServerStream", svc, method)
		w.Printf("func (s *%s) %s(ctx context.Context, req *%s, stream *%s) error {\n", gated, method, reqProto, streamType)
		w.Indented(func(w *Writer) {
			w.Printf("if err := s.authorize(ctx, %q, %s); err != nil {\n", a.Name, args)
			w.Indented(func(w *Writer) { w.Printf("return err\n") })
			w.Printf("}\n")
			w.Printf("return s.Inner.%s(ctx, req, stream)\n", method)
		})
		w.Printf("}\n\n")
		return
	}

	var retType string
	switch {
	case a.Response == nil:
		retType = "wkt.Empty"
	case a.Response.Use != nil:
		retType = *a.Response.Use
	default:
		retType = fmt.Sprintf("pbaccess.Resource%sAction%sResponseDTO", svc, method)
	}

	w.Printf("func (s *%s) %s(ctx context.Context, req *%s) (*%s, error) {\n", gated, method, reqProto, retType)
	w.Indented(func(w *Writer) {
		w.Printf("if err := s.authorize(ctx, %q, %s); err != nil {\n", a.Name, args)
		w.Indented(func(w *Writer) { w.Printf("return nil, err\n") })
		w.Printf("}\n")
		w.Printf("return s.Inner.%s(ctx, req)\n", method)
	})
	w.Printf("}\n\n")
}
