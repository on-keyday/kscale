// GeneratePeering emits reconcile/peering_gen.go: one membership-driven peering
// controller per PeeringSpec, plus a deduplicated push helper per southbound
// method. Unlike GenerateReconcile (declarative-store fanout), the desired set is
// derived from the live stat cache — the shared helpers destFromBatch /
// DestStatSource live in the hand-written reconcile/peering_support.go.
func GeneratePeering(input *Input) []ReconcileFile {
	specs := input.Definition.Peering
	if len(specs) == 0 {
		return nil
	}
	var buf bytes.Buffer
	w := &Writer{W: &buf}
	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package reconcile\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "log/slog")
		w.Printf("%q\n", "sort")
		w.Printf("%q\n", "sync")
		w.Printf("%q\n", "time")
		w.Printf("\n")
		w.Printf("%q\n", "github.com/on-keyday/kscale/dpbroker")
		w.Printf("%q\n", "github.com/on-keyday/kscale/internal/safe")
		w.Printf("%q\n", "github.com/on-keyday/kscale/peer")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("%q\n", "github.com/on-keyday/kscale/rpc")
		w.Printf("%q\n", "github.com/on-keyday/kscale/stat")
	})
	w.Printf(")\n\n")

	for i := range specs {
		emitPeering(w, &specs[i])
	}
	emitStartPeerings(w, specs)
	// One push helper per distinct (service, method, request_field).
	seen := map[string]bool{}
	for i := range specs {
		s := &specs[i]
		if seen[s.Method] {
			continue
		}
		seen[s.Method] = true
		emitPeeringPush(w, s)
	}

	return []ReconcileFile{{
		Path:    filepath.Join("reconcile", "peering_gen.go"),
		Content: buf.String(),
	}}
}

func emitPeering(w *Writer, s *PeeringSpec) {
	fn := "Peering" + toCamelCase(s.Source) + toCamelCase(s.Target)
	w.Printf("// %s reconciles the %q->%q peering: derive the %s nodes that pass the\n", fn, s.Source, s.Target, s.Source)
	w.Printf("// membership gate (running + bound + ServerID) from the stat cache and push\n")
	w.Printf("// them to every %s node via %s.%s on a tick and on node connect.\n", s.Target, s.Service, s.Method)
	w.Printf("func %s(ctx context.Context, cache DestStatSource, broker *dpbroker.Broker, logger *slog.Logger) {\n", fn)
	w.Indented(func(w *Writer) {
		w.Printf("var mu sync.Mutex\n")
		w.Printf("mgrs := map[string]*stat.DestManager{}\n")
		w.Printf("started := time.Now()\n\n")
		w.Printf("reconcile := func() {\n")
		w.Indented(func(w *Writer) {
			w.Printf("mu.Lock()\n")
			w.Printf("defer mu.Unlock()\n")
			w.Printf("var sources []stat.DestEntry\n")
			w.Printf("for _, p := range broker.List(%q) {\n", s.Source)
			w.Indented(func(w *Writer) {
				w.Printf("entry, err := destFromBatch(cache.Get(p.CommonName()))\n")
				w.Printf("if err != nil {\n")
				w.Indented(func(w *Writer) {
					w.Printf("if err != stat.ErrNoBoundInterface {\n")
					w.Indented(func(w *Writer) {
						w.Printf("logger.Debug(%q, \"node\", p.CommonName(), \"error\", err)\n", "peering: skip source node")
					})
					w.Printf("}\n")
					w.Printf("continue\n")
				})
				w.Printf("}\n")
				w.Printf("sources = append(sources, entry)\n")
			})
			w.Printf("}\n")
			w.Printf("sort.Slice(sources, func(i, j int) bool { return sources[i].ServerID < sources[j].ServerID })\n\n")
			w.Printf("live := map[string]struct{}{}\n")
			w.Printf("for _, p := range broker.List(%q) {\n", s.Target)
			w.Indented(func(w *Writer) {
				w.Printf("cn := p.CommonName()\n")
				w.Printf("live[cn] = struct{}{}\n")
				w.Printf("// Right after the CP starts, the stat cache is empty and fills node by node,\n")
				w.Printf("// so no sources yet usually means \"not reported yet\", not \"all gone\":\n")
				w.Printf("// hold off rather than shrink the target to nothing (see peeringStartupGrace).\n")
				w.Printf("if len(sources) == 0 && time.Since(started) < peeringStartupGrace {\n")
				w.Indented(func(w *Writer) {
					w.Printf("logger.Debug(%q, \"node\", cn)\n", "peering: no sources yet during startup grace; not pushing")
					w.Printf("continue\n")
				})
				w.Printf("}\n")
				w.Printf("dests := sources\n")
				if s.PrependSelf {
					w.Printf("// dest[0] = this target's own front (the eBPF source-fill slot).\n")
					w.Printf("self, err := destFromBatch(cache.Get(cn))\n")
					w.Printf("if err != nil {\n")
					w.Indented(func(w *Writer) {
						w.Printf("logger.Debug(%q, \"node\", cn, \"error\", err)\n", "peering: target not ready for self entry")
						w.Printf("continue\n")
					})
					w.Printf("}\n")
					w.Printf("dests = append([]stat.DestEntry{self}, sources...)\n")
				}
				w.Printf("mgr := mgrs[cn]\n")
				w.Printf("if mgr == nil {\n")
				w.Indented(func(w *Writer) {
					w.Printf("mgr = &stat.DestManager{}\n")
					w.Printf("mgrs[cn] = mgr\n")
				})
				w.Printf("}\n")
				w.Printf("p := p\n")
				w.Printf("if err := mgr.UpdateIfDiffer(dests, func(d []stat.DestEntry) error {\n")
				w.Indented(func(w *Writer) {
					w.Printf("return push%s(ctx, p, d, logger)\n", toCamelCase(s.Method))
				})
				w.Printf("}); err != nil {\n")
				w.Indented(func(w *Writer) {
					w.Printf("logger.Error(%q, \"node\", cn, \"error\", err)\n", "peering: push failed")
				})
				w.Printf("}\n")
			})
			w.Printf("}\n")
			w.Printf("for cn := range mgrs {\n")
			w.Indented(func(w *Writer) {
				w.Printf("if _, ok := live[cn]; !ok {\n")
				w.Indented(func(w *Writer) { w.Printf("delete(mgrs, cn)\n") })
				w.Printf("}\n")
			})
			w.Printf("}\n")
		})
		w.Printf("}\n\n")
		w.Printf("broker.OnConnect(func(dpType string, p *peer.Peer) {\n")
		w.Indented(func(w *Writer) {
			w.Printf("if dpbroker.Matches(%q, dpType) {\n", s.Target)
			w.Indented(func(w *Writer) {
				w.Printf("mu.Lock()\n")
				w.Printf("delete(mgrs, p.CommonName())\n")
				w.Printf("mu.Unlock()\n")
			})
			w.Printf("}\n")
			w.Printf("reconcile()\n")
		})
		w.Printf("})\n\n")
		w.Printf("go func() {\n")
		w.Indented(func(w *Writer) {
			w.Printf("defer safe.Recover(logger, %q)\n", "peering")
			w.Printf("t := time.NewTicker(3 * time.Second)\n")
			w.Printf("defer t.Stop()\n")
			w.Printf("for {\n")
			w.Indented(func(w *Writer) {
				w.Printf("select {\n")
				w.Printf("case <-ctx.Done():\n")
				w.Indented(func(w *Writer) { w.Printf("return\n") })
				w.Printf("case <-t.C:\n")
				w.Indented(func(w *Writer) { w.Printf("reconcile()\n") })
				w.Printf("}\n")
			})
			w.Printf("}\n")
		})
		w.Printf("}()\n")
	})
	w.Printf("}\n\n")
}

// emitStartPeerings emits StartPeerings, which starts every declared binding. The
// control plane calls this one entry point, so a new `peering:` entry in
// resource.yaml is live without a matching hand edit in cmd/controlplane.
func emitStartPeerings(w *Writer, specs []PeeringSpec) {
	w.Printf("// StartPeerings starts every peering controller declared in resource.yaml.\n")
	w.Printf("func StartPeerings(ctx context.Context, cache DestStatSource, broker *dpbroker.Broker, logger *slog.Logger) {\n")
	w.Indented(func(w *Writer) {
		for i := range specs {
			w.Printf("Peering%s%s(ctx, cache, broker, logger)\n", toCamelCase(specs[i].Source), toCamelCase(specs[i].Target))
		}
	})
	w.Printf("}\n\n")
}

func emitPeeringPush(w *Writer, s *PeeringSpec) {
	fn := "push" + toCamelCase(s.Method)
	reqType := fmt.Sprintf("pb.%s%sRequest", s.Service, s.Method)
	reqField := toCamelCase(s.RequestField)
	w.Printf("func %s(ctx context.Context, p *peer.Peer, dests []stat.DestEntry, logger *slog.Logger) error {\n", fn)
	w.Indented(func(w *Writer) {
		w.Printf("c := pb.New%sClient(rpc.NewTrsfStreamSource(p.Streams(), logger))\n", s.Service)
		w.Printf("req := &%s{}\n", reqType)
		w.Printf("for _, d := range dests {\n")
		w.Indented(func(w *Writer) {
			w.Printf("req.%s = append(req.%s, &pb.Destination{\n", reqField, reqField)
			w.Indented(func(w *Writer) {
				w.Printf("ServerId:     d.ServerID,\n")
				w.Printf("HardwareAddr: d.HardwareAddr,\n")
				w.Printf("IpAddr:       d.IPAddr.String(),\n")
			})
			w.Printf("})\n")
		})
		w.Printf("}\n")
		w.Printf("_, err := c.%s(ctx, req)\n", s.Method)
		w.Printf("if err == nil {\n")
		w.Indented(func(w *Writer) {
			w.Printf("logger.Info(%q, \"node\", p.CommonName(), \"count\", len(dests))\n", "peering: pushed")
		})
		w.Printf("}\n")
		w.Printf("return err\n")
	})
	w.Printf("}\n\n")
}
