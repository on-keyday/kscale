package generator

import (
	"bytes"
	"fmt"
	"path/filepath"
	"sort"
	"strings"
)

// ClientDispatchFile is one generated client-dispatch Go file: a repo-relative
// output path plus its full source. GenerateClientDispatch returns one per
// rpc_service resource; cmd/gen writes them into the client package.
type ClientDispatchFile struct {
	Path    string
	Content string
}

// GenerateClientDispatch emits, for every resource with rpc_service: true, a
// Dispatch{Resource}(ctx, c, action, args) helper that maps one CLI-style
// invocation onto the generated typed RPC client: it switches on the action's
// command_name, binds the request DTO from the args map (string fields direct,
// integer/duration fields parsed), calls the typed client method, and renders
// the response as JSON ("" for no-response actions). This is the client-side
// twin of the gate adapter — the typed-RPC replacement for the hand-written
// per-action switch in cmd/cli (kscale charter M4.2). Args carrier is a
// map[string]string (A); rendering is JSON (B); the dispatch key is command_name
// (C).
func GenerateClientDispatch(input *Input) []ClientDispatchFile {
	var files []ClientDispatchFile
	for _, r := range input.Definition.Resources {
		if !r.generatesGate() {
			continue
		}
		var buf bytes.Buffer
		emitClientDispatch(&Writer{W: &buf}, &r)
		files = append(files, ClientDispatchFile{
			Path:    filepath.Join("client", r.Name+"_dispatch_gen.go"),
			Content: buf.String(),
		})
	}
	return files
}

// GenerateClientRouter emits client/dispatch_router_gen.go: a single
// DispatchResource(ctx, src, resource, action, args) that routes by the
// resource's command_name to its generated Dispatch{Resource}, building the typed
// client from src. Generated from resource.yaml so carving a resource enrolls it
// in the CLI router automatically (no hand-maintained switch).
func GenerateClientRouter(input *Input) ClientDispatchFile {
	var buf bytes.Buffer
	w := &Writer{W: &buf}
	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package client\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "fmt")
		w.Printf("\n")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("%q\n", "github.com/on-keyday/kscale/protobuf/wire")
	})
	w.Printf(")\n\n")
	w.Printf("// DispatchResource routes a `<resource> <action> [args]` invocation to the\n")
	w.Printf("// matching generated typed-RPC dispatch, building the per-resource client from\n")
	w.Printf("// src. resource is the resource's command_name.\n")
	w.Printf("func DispatchResource(ctx context.Context, src *wire.StreamSource, resource, action string, args map[string]string) (string, error) {\n")
	w.Indented(func(w *Writer) {
		w.Printf("switch resource {\n")
		for i := range input.Definition.Resources {
			r := &input.Definition.Resources[i]
			if !r.generatesGate() {
				continue
			}
			svc := toCamelCase(r.Name)
			w.Printf("case %q:\n", primaryCommandName(r))
			w.Indented(func(w *Writer) {
				w.Printf("return Dispatch%s(ctx, pb.New%sServiceClient(src), action, args)\n", svc, svc)
			})
		}
		w.Printf("default:\n")
		w.Indented(func(w *Writer) {
			w.Printf("return \"\", fmt.Errorf(%q, resource)\n", "unknown resource %q")
		})
		w.Printf("}\n")
	})
	w.Printf("}\n")
	return ClientDispatchFile{Path: filepath.Join("client", "dispatch_router_gen.go"), Content: buf.String()}
}

// primaryCommandName returns a resource's first command_name (its router key),
// falling back to its name.
func primaryCommandName(r *ResourceTemplate) string {
	if len(r.CommandName) > 0 {
		return r.CommandName[0]
	}
	return r.Name
}

// GenerateClientUsage emits client/usage_gen.go: a Usage() string listing each
// resource (by command_name) and its actions with the --arg names they accept,
// generated from resource.yaml so the CLI help stays in sync with the resources.
func GenerateClientUsage(input *Input) ClientDispatchFile {
	type row struct{ name, actions string }
	type argspec struct{ name, typ, def string }
	type actSpec struct {
		cmd    string
		args   []argspec
		stream bool
		desc   string
	}
	var rows []row
	var resOrder []string
	specs := map[string]map[string][]argspec{} // resource cmd -> action cmd -> args
	resSpecs := map[string][]actSpec{}         // resource cmd -> ordered actions (richer)
	width := 0
	for i := range input.Definition.Resources {
		r := &input.Definition.Resources[i]
		if !r.generatesGate() {
			continue
		}
		name := primaryCommandName(r)
		if len(name) > width {
			width = len(name)
		}
		resOrder = append(resOrder, name)
		specs[name] = map[string][]argspec{}
		var parts []string
		for _, a := range r.rpcActions() {
			act := commandNames(&a)[0]
			var as []argspec
			for _, arg := range a.Args {
				def := ""
				if arg.Default != nil {
					def = *arg.Default
				}
				as = append(as, argspec{arg.Name, arg.Type, def})
			}
			specs[name][act] = as
			stream := a.Response != nil && a.Response.Stream
			resSpecs[name] = append(resSpecs[name], actSpec{cmd: act, args: as, stream: stream, desc: r.Monitor[act]})
			if len(a.Args) > 0 {
				names := make([]string, len(a.Args))
				for j, arg := range a.Args {
					// Display the kebab-case flag spelling (the CLI registers
					// flags that way); the dispatch/args-map key stays snake.
					names[j] = strings.ReplaceAll(arg.Name, "_", "-")
				}
				act += " [" + strings.Join(names, " ") + "]"
			}
			parts = append(parts, act)
		}
		rows = append(rows, row{name, strings.Join(parts, " | ")})
	}
	var content strings.Builder
	content.WriteString("resources (--resource <name> --op <action>; pass action args as typed --<arg> flags):\n")
	for _, r := range rows {
		fmt.Fprintf(&content, "  %-*s  %s\n", width, r.name, r.actions)
	}

	var buf bytes.Buffer
	w := &Writer{W: &buf}
	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package client\n\n")
	w.Printf("// Usage returns generated CLI help: each resource (by command_name) and its\n")
	w.Printf("// actions with the arg names they accept (passed as --<arg> flags).\n")
	w.Printf("func Usage() string {\n")
	w.Printf("\treturn %q\n", content.String())
	w.Printf("}\n\n")

	// ArgSpec table so the CLI can expose one typed --<arg> flag per action arg
	// (discoverable in -h) instead of a generic --arg name=value.
	w.Printf("// ArgSpec describes one action arg the CLI exposes as a --<Name> flag.\n")
	w.Printf("type ArgSpec struct{ Name, Type, Default string }\n\n")
	w.Printf("var actionArgs = map[string]map[string][]ArgSpec{\n")
	for _, rname := range resOrder {
		w.Printf("\t%q: {\n", rname)
		acts := make([]string, 0, len(specs[rname]))
		for act := range specs[rname] {
			acts = append(acts, act)
		}
		sort.Strings(acts)
		for _, act := range acts {
			w.Printf("\t\t%q: {", act)
			for _, s := range specs[rname][act] {
				w.Printf("{Name: %q, Type: %q, Default: %q}, ", s.name, s.typ, s.def)
			}
			w.Printf("},\n")
		}
		w.Printf("\t},\n")
	}
	w.Printf("}\n\n")
	w.Printf("// ActionArgs returns the declared args for a resource action (both by\n")
	w.Printf("// command_name) and whether the resource/action is known.\n")
	w.Printf("func ActionArgs(resource, action string) ([]ArgSpec, bool) {\n")
	w.Printf("\tacts, ok := actionArgs[resource]\n")
	w.Printf("\tif !ok {\n\t\treturn nil, false\n\t}\n")
	w.Printf("\ta, ok := acts[action]\n")
	w.Printf("\treturn a, ok\n")
	w.Printf("}\n\n")

	// ResourceSpecs: a structured registry (resources -> actions -> args + stream,
	// all by command_name) so programmatic clients — yaml-apply, the admin TUI —
	// drive off the same single source as the CLI, with no per-resource code.
	w.Printf("// ActionSpec / ResourceSpec describe a resource action / resource by\n")
	w.Printf("// command_name, for metadata-driven clients (yaml-apply, the admin TUI).\n")
	w.Printf("type ActionSpec struct {\n")
	w.Printf("\tCommand string\n\tArgs []ArgSpec\n\tStream bool\n\tDescription string\n")
	w.Printf("}\n\n")
	w.Printf("type ResourceSpec struct {\n")
	w.Printf("\tCommand string\n\tActions []ActionSpec\n")
	w.Printf("}\n\n")
	w.Printf("var ResourceSpecs = []ResourceSpec{\n")
	for _, rname := range resOrder {
		w.Printf("\t{Command: %q, Actions: []ActionSpec{\n", rname)
		for _, a := range resSpecs[rname] {
			w.Printf("\t\t{Command: %q, Stream: %t, ", a.cmd, a.stream)
			if a.desc != "" {
				w.Printf("Description: %q, ", a.desc)
			}
			w.Printf("Args: []ArgSpec{")
			for _, s := range a.args {
				w.Printf("{Name: %q, Type: %q, Default: %q}, ", s.name, s.typ, s.def)
			}
			w.Printf("}},\n")
		}
		w.Printf("\t}},\n")
	}
	w.Printf("}\n\n")
	w.Printf("// SpecFor returns a resource's spec by command_name.\n")
	w.Printf("func SpecFor(resource string) (ResourceSpec, bool) {\n")
	w.Printf("\tfor _, r := range ResourceSpecs {\n\t\tif r.Command == resource {\n\t\t\treturn r, true\n\t\t}\n\t}\n\treturn ResourceSpec{}, false\n")
	w.Printf("}\n\n")
	w.Printf("// ActionSpecFor returns a resource action's spec by command_names.\n")
	w.Printf("func ActionSpecFor(resource, action string) (ActionSpec, bool) {\n")
	w.Printf("\tr, ok := SpecFor(resource)\n\tif !ok {\n\t\treturn ActionSpec{}, false\n\t}\n")
	w.Printf("\tfor _, a := range r.Actions {\n\t\tif a.Command == action {\n\t\t\treturn a, true\n\t\t}\n\t}\n\treturn ActionSpec{}, false\n")
	w.Printf("}\n")
	return ClientDispatchFile{Path: filepath.Join("client", "usage_gen.go"), Content: buf.String()}
}

// dispatchNeedsStrconv reports whether any bound arg of any action needs strconv
// (i.e. a non-string field), so the import is only emitted when used.
func dispatchNeedsStrconv(r *ResourceTemplate) bool {
	for _, a := range r.rpcActions() {
		for _, arg := range a.Args {
			if isIntegerArg(arg.Type) {
				return true
			}
		}
	}
	return false
}

// dispatchNeedsStream reports whether any action is server-streaming, so the
// streaming-only imports (errors, io) are emitted only when used.
func dispatchNeedsStream(r *ResourceTemplate) bool {
	for _, a := range r.rpcActions() {
		if a.isStreamingResponse() {
			return true
		}
	}
	return false
}

// dtoIntGoType returns the Go type of the DTO field a parsed integer arg is
// assigned to, so the int64 from strconv.ParseInt is cast correctly (a uint32
// field needs uint32(n), not n). time.Duration and other ints land in an int64
// field, mirroring goTypeToProtoType.
func dtoIntGoType(argType string) string {
	switch argType {
	case "uint32":
		return "uint32"
	case "uint64":
		return "uint64"
	default:
		return "int64"
	}
}

// isStringArg reports whether the arg's yaml type maps to a proto string field.
func isStringArg(t string) bool { return t == "string" }

// isIntegerArg reports whether the arg's yaml type maps to a proto integer field
// (parsed from the args map with strconv.ParseInt). time.Duration is wire-encoded
// as an int64.
func isIntegerArg(t string) bool {
	switch t {
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64":
		return true
	}
	return false
}

// isDurationArg reports whether the arg is a time.Duration (held as such on the
// DTO via the (ksdk.hold) option), bound from the args map with time.ParseDuration
// so "5m" works on the CLI.
func isDurationArg(t string) bool { return t == "time.Duration" }

func isBytesArg(t string) bool { return t == "[]byte" }

// dispatchNeedsOS reports whether any bound arg is []byte, which the dispatch
// binds by reading the arg value as a file path (os.ReadFile).
func dispatchNeedsOS(r *ResourceTemplate) bool {
	for _, a := range r.rpcActions() {
		for _, arg := range a.Args {
			if isBytesArg(arg.Type) {
				return true
			}
		}
	}
	return false
}

// dispatchNeedsTime reports whether any action has a time.Duration arg, so the
// "time" import is emitted only when used.
func dispatchNeedsTime(r *ResourceTemplate) bool {
	for _, a := range r.rpcActions() {
		for _, arg := range a.Args {
			if isDurationArg(arg.Type) {
				return true
			}
		}
	}
	return false
}

func emitClientDispatch(w *Writer, r *ResourceTemplate) {
	svc := toCamelCase(r.Name) // CaManagement
	needStrconv := dispatchNeedsStrconv(r)
	needStream := dispatchNeedsStream(r)
	needTime := dispatchNeedsTime(r)
	needOS := dispatchNeedsOS(r)

	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package client\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "encoding/json")
		if needStream {
			w.Printf("%q\n", "errors")
		}
		w.Printf("%q\n", "fmt")
		if needStream {
			w.Printf("%q\n", "io")
		}
		if needOS {
			w.Printf("%q\n", "os")
		}
		if needStrconv {
			w.Printf("%q\n", "strconv")
		}
		if needTime {
			w.Printf("%q\n", "time")
		}
		w.Printf("\n")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("pbaccess %q\n", "github.com/on-keyday/kscale/protobuf/proto/access")
	})
	w.Printf(")\n\n")

	w.Printf("// Dispatch%s maps one `<action-command> [args]` invocation to its typed\n", svc)
	w.Printf("// %sService RPC: it binds the request DTO from args (keyed by the yaml arg\n", svc)
	w.Printf("// names), calls the typed client, and returns the response as JSON (\"\" for\n")
	w.Printf("// no-response actions). action is the action's command_name.\n")
	w.Printf("func Dispatch%s(ctx context.Context, c pb.%sServiceClient, action string, args map[string]string) (string, error) {\n", svc, svc)
	w.Indented(func(w *Writer) {
		w.Printf("switch action {\n")
		for _, a := range r.rpcActions() {
			emitClientDispatchCase(w, svc, &a)
		}
		w.Printf("default:\n")
		w.Indented(func(w *Writer) {
			w.Printf("return \"\", fmt.Errorf(%q, action)\n", "unknown action %q")
		})
		w.Printf("}\n")
	})
	w.Printf("}\n\n")
}

func emitClientDispatchCase(w *Writer, svc string, a *Action) {
	method := toCamelCase(a.Name)
	reqProto := fmt.Sprintf("pbaccess.Resource%sAction%sArgsDTO", svc, method)

	for _, cmd := range commandNames(a) {
		w.Printf("case %q:\n", cmd)
	}
	w.Indented(func(w *Writer) {
		w.Printf("dto := &%s{}\n", reqProto)
		for _, arg := range a.Args {
			field := toCamelCase(arg.Name)
			switch {
			case isStringArg(arg.Type):
				// Apply the declared default when the arg is absent (the CLI only
				// sends explicitly-set flags), else the empty string.
				if arg.Default != nil {
					w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
					w.Indented(func(w *Writer) { w.Printf("dto.%s = v\n", field) })
					w.Printf("} else {\n")
					w.Indented(func(w *Writer) { w.Printf("dto.%s = %q\n", field, *arg.Default) })
					w.Printf("}\n")
				} else {
					w.Printf("dto.%s = args[%q]\n", field, arg.Name)
				}
			case isBytesArg(arg.Type):
				// []byte binds from a file path: --arg <name>=/path/to/file.
				w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
				w.Indented(func(w *Writer) {
					w.Printf("b, err := os.ReadFile(v)\n")
					w.Printf("if err != nil {\n")
					w.Indented(func(w *Writer) {
						w.Printf("return \"\", fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w")
					})
					w.Printf("}\n")
					w.Printf("dto.%s = b\n", field)
				})
				w.Printf("}\n")
			case isDurationArg(arg.Type):
				w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
				w.Indented(func(w *Writer) {
					w.Printf("d, err := time.ParseDuration(v)\n")
					w.Printf("if err != nil {\n")
					w.Indented(func(w *Writer) {
						w.Printf("return \"\", fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w")
					})
					w.Printf("}\n")
					w.Printf("dto.%s = d\n", field)
				})
				w.Printf("}\n")
			case isIntegerArg(arg.Type):
				w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
				w.Indented(func(w *Writer) {
					w.Printf("n, err := strconv.ParseInt(v, 10, 64)\n")
					w.Printf("if err != nil {\n")
					w.Indented(func(w *Writer) {
						w.Printf("return \"\", fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w")
					})
					w.Printf("}\n")
					// ParseInt yields int64; cast to the DTO field's Go type.
					w.Printf("dto.%s = %s(n)\n", field, dtoIntGoType(arg.Type))
				})
				w.Printf("}\n")
			case arg.Type == "[]string":
				// []string binds from a JSON array ('["a","b"]') or, shell-friendly,
				// a comma-separated list (a,b) — see client.parseStringList.
				w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
				w.Indented(func(w *Writer) {
					w.Printf("l, err := parseStringList(v)\n")
					w.Printf("if err != nil {\n")
					w.Indented(func(w *Writer) {
						w.Printf("return \"\", fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w")
					})
					w.Printf("}\n")
					w.Printf("dto.%s = l\n", field)
				})
				w.Printf("}\n")
			default:
				// Structured / complex field (e.g. []*pb.PortInfo): bind from a
				// JSON-valued arg, e.g. --arg ports='[{"port":80,"protocol":"tcp"}]'.
				w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
				w.Indented(func(w *Writer) {
					w.Printf("if err := json.Unmarshal([]byte(v), &dto.%s); err != nil {\n", field)
					w.Indented(func(w *Writer) {
						w.Printf("return \"\", fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w")
					})
					w.Printf("}\n")
				})
				w.Printf("}\n")
			}
		}
		if a.isStreamingResponse() {
			// Server-streaming: open the stream and render each element as JSON to
			// stdout until io.EOF. Returns "" so the caller prints nothing extra.
			w.Printf("stream, err := c.%s(ctx, dto)\n", method)
			w.Printf("if err != nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
			w.Printf("}\n")
			w.Printf("for {\n")
			w.Indented(func(w *Writer) {
				w.Printf("item, err := stream.Recv(ctx)\n")
				w.Printf("if errors.Is(err, io.EOF) {\n")
				w.Indented(func(w *Writer) { w.Printf("break\n") })
				w.Printf("}\n")
				w.Printf("if err != nil {\n")
				w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
				w.Printf("}\n")
				w.Printf("b, err := json.MarshalIndent(item, \"\", \"  \")\n")
				w.Printf("if err != nil {\n")
				w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
				w.Printf("}\n")
				w.Printf("fmt.Println(string(b))\n")
			})
			w.Printf("}\n")
			w.Printf("return \"\", nil\n")
			return
		}
		if a.Response == nil {
			w.Printf("if _, err := c.%s(ctx, dto); err != nil {\n", method)
			w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
			w.Printf("}\n")
			w.Printf("return \"\", nil\n")
			return
		}
		w.Printf("resp, err := c.%s(ctx, dto)\n", method)
		w.Printf("if err != nil {\n")
		w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
		w.Printf("}\n")
		w.Printf("b, err := json.MarshalIndent(resp, \"\", \"  \")\n")
		w.Printf("if err != nil {\n")
		w.Indented(func(w *Writer) { w.Printf("return \"\", err\n") })
		w.Printf("}\n")
		w.Printf("return string(b), nil\n")
	})
}

// commandNames returns the action's command_name(s), falling back to the action
// name when none is declared.
func commandNames(a *Action) []string {
	if len(a.CommandName) > 0 {
		return []string(a.CommandName)
	}
	return []string{a.Name}
}
