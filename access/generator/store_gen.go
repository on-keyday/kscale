package generator

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
)

// StoreFile is one generated declarative-store Go file.
type StoreFile struct {
	Path    string
	Content string
}

// GenerateStore emits, for every declarative resource opted in via
// schema.generated_store, a synthesized backing store into service/<pkg>/store_gen.go:
// the map[key]*DTO that apply upserts and get/list/delete read, plus (when the resource
// is reconciled) OnChange/notify/Desired + a ConfirmPush hook, plus Snapshot/Restore for
// desired-state persistence. `sensitive` fields are blanked from northbound responses by
// a generated redacted() (kept full in Desired, which feeds the reconcile push). This
// replaces the hand-written service/<pkg>/handlers.go + persist.go (gate/business split:
// only genuinely bespoke stores — vip, secret — stay hand-written).
func GenerateStore(input *Input) []StoreFile {
	var files []StoreFile
	for i := range input.Definition.Resources {
		r := &input.Definition.Resources[i]
		if r.Schema == nil || !r.Schema.GeneratedStore {
			continue
		}
		var buf bytes.Buffer
		emitStore(&Writer{W: &buf}, r)
		files = append(files, StoreFile{
			Path:    filepath.Join("service", storePkg(r.Name), "store_gen.go"),
			Content: buf.String(),
		})
	}
	return files
}

// storePkg maps a resource name to its service package dir/name (underscores dropped:
// open_port -> openport, popcache_config -> popcacheconfig).
func storePkg(name string) string { return strings.ReplaceAll(name, "_", "") }

func hasCRUD(r *ResourceTemplate, verb string) bool {
	for i := range r.Actions {
		if r.Actions[i].Name == verb {
			return true
		}
	}
	return false
}

func sensitiveFields(s *ResourceSchema) []ActionArg {
	var out []ActionArg
	for _, f := range s.Fields {
		if f.Sensitive {
			out = append(out, f)
		}
	}
	return out
}

func nonSensitiveFields(s *ResourceSchema) []ActionArg {
	var out []ActionArg
	for _, f := range s.Fields {
		if !f.Sensitive {
			out = append(out, f)
		}
	}
	return out
}

func emitStore(w *Writer, r *ResourceTemplate) {
	svc := toCamelCase(r.Name) // OpenPort
	dto := "pbaccess.Resource" + svc + "Action"
	getDTO := dto + "GetResponseDTO"
	key := keyField(r.Schema)
	keyCamel := toCamelCase(key.Name)
	keyType := goTypeOf(key.Type)
	reconciled := r.Schema.Reconcile != nil
	sensitive := len(sensitiveFields(r.Schema)) > 0
	mapType := fmt.Sprintf("map[%s]*%s", keyType, getDTO)

	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package %s\n\n", storePkg(r.Name))
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "encoding/json")
		w.Printf("%q\n", "fmt")
		w.Printf("%q\n", "sort")
		w.Printf("%q\n", "sync")
		w.Printf("\n")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("pbaccess %q\n", "github.com/on-keyday/kscale/protobuf/proto/access")
	})
	w.Printf(")\n\n")

	// Struct + constructor + interface assertion.
	w.Printf("// Handlers is the generated %s desired-state store.\n", r.Name)
	w.Printf("type Handlers struct {\n")
	w.Indented(func(w *Writer) {
		w.Printf("pb.Unimplemented%sServiceServer\n", svc)
		w.Printf("mu    sync.Mutex\n")
		w.Printf("store %s\n", mapType)
		if reconciled {
			w.Printf("onChange []func()\n")
			w.Printf("// ConfirmPush, set by the control plane, returns the resource's current per-node\n")
			w.Printf("// reconcile push error (nil if all good); called right after notify() so apply\n")
			w.Printf("// reports a failed push synchronously instead of a silent OK. Optional.\n")
			w.Printf("ConfirmPush func() error\n")
		}
	})
	w.Printf("}\n\n")
	w.Printf("var _ pb.%sServiceServer = (*Handlers)(nil)\n\n", svc)
	w.Printf("// New returns an empty %s store.\n", r.Name)
	w.Printf("func New() *Handlers { return &Handlers{store: %s{}} }\n\n", mapType)

	// redacted() — blank sensitive fields for northbound responses.
	if sensitive {
		w.Printf("// redacted returns a copy with sensitive fields blanked — what northbound callers\n")
		w.Printf("// see. The sensitive values are write-only: pushed to the node by reconcile (which\n")
		w.Printf("// reads the full Desired()), never returned.\n")
		w.Printf("func redacted(c *%s) *%s {\n", getDTO, getDTO)
		w.Indented(func(w *Writer) {
			w.Printf("if c == nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return nil\n") })
			w.Printf("}\n")
			w.Printf("return &%s{\n", getDTO)
			w.Indented(func(w *Writer) {
				for _, f := range nonSensitiveFields(r.Schema) {
					fc := toCamelCase(f.Name)
					w.Printf("%s: c.%s,\n", fc, fc)
				}
			})
			w.Printf("}\n")
		})
		w.Printf("}\n\n")
	}

	emitStoreApply(w, r, svc, dto, getDTO, keyCamel, reconciled, sensitive)
	if hasCRUD(r, "get") {
		emitStoreGet(w, r, dto, getDTO, keyCamel, keyType, sensitive)
	}
	if hasCRUD(r, "list") {
		emitStoreList(w, r, dto, getDTO, keyType, sensitive)
	}
	if hasCRUD(r, "delete") {
		emitStoreDelete(w, dto, keyCamel, reconciled)
	}
	if reconciled {
		emitStoreReconcileSurface(w, getDTO)
	}
	emitStorePersist(w, mapType)
}

// itemExpr wraps a stored *GetDTO in redacted() for northbound responses when the
// resource has sensitive fields.
func itemExpr(expr string, sensitive bool) string {
	if sensitive {
		return "redacted(" + expr + ")"
	}
	return expr
}

func emitStoreApply(w *Writer, r *ResourceTemplate, svc, dto, getDTO, keyCamel string, reconciled, sensitive bool) {
	applyArgs := dto + "ApplyArgsDTO"
	applyResp := dto + "ApplyResponseDTO"
	respFields := r.Schema.Fields
	if sensitive {
		respFields = nonSensitiveFields(r.Schema)
	}
	readonly := readonlyFields(r.Schema)
	w.Printf("// Apply idempotently upserts one %s by %s.\n", r.Name, keyCamel)
	w.Printf("func (h *Handlers) Apply(ctx context.Context, req *%s) (*%s, error) {\n", applyArgs, applyResp)
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		if !reconciled {
			w.Printf("defer h.mu.Unlock()\n")
		}
		if len(readonly) > 0 {
			w.Printf("// readonly fields are not client-settable: carry them over from any\n")
			w.Printf("// existing entry so a re-apply (e.g. deploy tooling rewriting the\n")
			w.Printf("// inventory) doesn't wipe internally-managed state.\n")
			w.Printf("prev := h.store[req.%s]\n", keyCamel)
		}
		w.Printf("obj := &%s{\n", getDTO)
		w.Indented(func(w *Writer) {
			for _, f := range r.Schema.Fields {
				if f.ReadOnly {
					continue
				}
				fc := toCamelCase(f.Name)
				w.Printf("%s: req.%s,\n", fc, fc)
			}
		})
		w.Printf("}\n")
		if len(readonly) > 0 {
			w.Printf("if prev != nil {\n")
			w.Indented(func(w *Writer) {
				for _, f := range readonly {
					fc := toCamelCase(f.Name)
					w.Printf("obj.%s = prev.%s\n", fc, fc)
				}
			})
			w.Printf("}\n")
		}
		w.Printf("h.store[req.%s] = obj\n", keyCamel)
		// The response is built while still locked: readonly fields read from obj,
		// which stays reachable through the store map and may be replaced/updated
		// concurrently once the lock is released.
		w.Printf("resp := &%s{\n", applyResp)
		w.Indented(func(w *Writer) {
			for _, f := range respFields {
				fc := toCamelCase(f.Name)
				if f.ReadOnly {
					w.Printf("%s: obj.%s,\n", fc, fc)
				} else {
					w.Printf("%s: req.%s,\n", fc, fc)
				}
			}
		})
		w.Printf("}\n")
		if reconciled {
			w.Printf("h.mu.Unlock()\n")
			w.Printf("h.notify()\n")
		}
		if reconciled {
			w.Printf("if h.ConfirmPush != nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return resp, h.ConfirmPush()\n") })
			w.Printf("}\n")
		}
		w.Printf("return resp, nil\n")
	})
	w.Printf("}\n\n")
}

// readonlyFields returns the schema fields marked readonly (computed/internally
// managed, excluded from apply args and preserved across apply).
func readonlyFields(s *ResourceSchema) []ActionArg {
	var out []ActionArg
	for _, f := range s.Fields {
		if f.ReadOnly {
			out = append(out, f)
		}
	}
	return out
}

func emitStoreGet(w *Writer, r *ResourceTemplate, dto, getDTO, keyCamel, keyType string, sensitive bool) {
	verb := "%q"
	if keyType != "string" {
		verb = "%v"
	}
	w.Printf("// Get returns one %s by %s.\n", r.Name, keyCamel)
	w.Printf("func (h *Handlers) Get(ctx context.Context, req *%sGetArgsDTO) (*%s, error) {\n", dto, getDTO)
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("defer h.mu.Unlock()\n")
		w.Printf("obj, ok := h.store[req.%s]\n", keyCamel)
		w.Printf("if !ok {\n")
		w.Indented(func(w *Writer) {
			w.Printf("return nil, fmt.Errorf(%q, req.%s)\n", r.Name+" "+verb+" not found", keyCamel)
		})
		w.Printf("}\n")
		w.Printf("return %s, nil\n", itemExpr("obj", sensitive))
	})
	w.Printf("}\n\n")
}

func emitStoreList(w *Writer, r *ResourceTemplate, dto, getDTO, keyType string, sensitive bool) {
	w.Printf("// List returns every %s (sorted by key for determinism).\n", r.Name)
	w.Printf("func (h *Handlers) List(ctx context.Context, _ *%sListArgsDTO) (*%sListResponseDTO, error) {\n", dto, dto)
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("defer h.mu.Unlock()\n")
		w.Printf("keys := make([]%s, 0, len(h.store))\n", keyType)
		w.Printf("for k := range h.store {\n")
		w.Indented(func(w *Writer) { w.Printf("keys = append(keys, k)\n") })
		w.Printf("}\n")
		if keyType == "string" {
			w.Printf("sort.Strings(keys)\n")
		} else {
			w.Printf("sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })\n")
		}
		w.Printf("items := make([]*%s, 0, len(keys))\n", getDTO)
		w.Printf("for _, k := range keys {\n")
		w.Indented(func(w *Writer) { w.Printf("items = append(items, %s)\n", itemExpr("h.store[k]", sensitive)) })
		w.Printf("}\n")
		w.Printf("return &%sListResponseDTO{Items: items}, nil\n", dto)
	})
	w.Printf("}\n\n")
}

func emitStoreDelete(w *Writer, dto, keyCamel string, reconciled bool) {
	w.Printf("// Delete removes one entry by %s.\n", keyCamel)
	w.Printf("func (h *Handlers) Delete(ctx context.Context, req *%sDeleteArgsDTO) (*%sDeleteResponseDTO, error) {\n", dto, dto)
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		if !reconciled {
			w.Printf("defer h.mu.Unlock()\n")
		}
		w.Printf("delete(h.store, req.%s)\n", keyCamel)
		if reconciled {
			w.Printf("h.mu.Unlock()\n")
			w.Printf("h.notify()\n")
		}
		w.Printf("return &%sDeleteResponseDTO{%s: req.%s}, nil\n", dto, keyCamel, keyCamel)
	})
	w.Printf("}\n\n")
}

// emitStoreReconcileSurface emits OnChange/notify/Desired — the desired-state source the
// generated reconcile controller consumes. Desired returns the FULL (unredacted) items.
func emitStoreReconcileSurface(w *Writer, getDTO string) {
	w.Printf("// OnChange registers a callback fired on every desired-state mutation — the\n")
	w.Printf("// reconcile loop subscribes to re-push to the dataplane.\n")
	w.Printf("func (h *Handlers) OnChange(f func()) {\n")
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("h.onChange = append(h.onChange, f)\n")
		w.Printf("h.mu.Unlock()\n")
	})
	w.Printf("}\n\n")

	w.Printf("func (h *Handlers) notify() {\n")
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("cbs := append([]func(){}, h.onChange...)\n")
		w.Printf("h.mu.Unlock()\n")
		w.Printf("for _, f := range cbs {\n")
		w.Indented(func(w *Writer) { w.Printf("f()\n") })
		w.Printf("}\n")
	})
	w.Printf("}\n\n")

	w.Printf("// Desired returns the full desired set (WITH sensitive fields) for the reconcile\n")
	w.Printf("// loop to push to the dataplane.\n")
	w.Printf("func (h *Handlers) Desired() []*%s {\n", getDTO)
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("defer h.mu.Unlock()\n")
		w.Printf("out := make([]*%s, 0, len(h.store))\n", getDTO)
		w.Printf("for _, c := range h.store {\n")
		w.Indented(func(w *Writer) { w.Printf("out = append(out, c)\n") })
		w.Printf("}\n")
		w.Printf("return out\n")
	})
	w.Printf("}\n\n")
}

// emitStorePersist emits Snapshot/Restore (desiredstate.Store) over the whole store map,
// INCLUDING sensitive fields — the desiredstate file is encrypted, so they round-trip.
func emitStorePersist(w *Writer, mapType string) {
	w.Printf("// Snapshot/Restore persist the desired state (desiredstate.Store). The full map\n")
	w.Printf("// (including sensitive fields) is serialized; the desiredstate file is encrypted.\n")
	w.Printf("func (h *Handlers) Snapshot() (json.RawMessage, error) {\n")
	w.Indented(func(w *Writer) {
		w.Printf("h.mu.Lock()\n")
		w.Printf("defer h.mu.Unlock()\n")
		w.Printf("return json.Marshal(h.store)\n")
	})
	w.Printf("}\n\n")

	w.Printf("func (h *Handlers) Restore(raw json.RawMessage) error {\n")
	w.Indented(func(w *Writer) {
		w.Printf("var m %s\n", mapType)
		w.Printf("if err := json.Unmarshal(raw, &m); err != nil {\n")
		w.Indented(func(w *Writer) { w.Printf("return err\n") })
		w.Printf("}\n")
		w.Printf("if m == nil {\n")
		w.Indented(func(w *Writer) { w.Printf("m = %s{}\n", mapType) })
		w.Printf("}\n")
		w.Printf("h.mu.Lock()\n")
		w.Printf("defer h.mu.Unlock()\n")
		w.Printf("h.store = m\n")
		w.Printf("return nil\n")
	})
	w.Printf("}\n")
}
