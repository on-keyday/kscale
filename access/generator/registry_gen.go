package generator

import (
	"fmt"
	"io"
	"sort"
)

// GenerateProtoRegistry emits a Go file that registers every generated
// pbaccess DTO type by short name. The admin RPC response receive path looks
// up the DTO by its short name (e.g.
// "ResourceCertificateActionGetResponseDTO"), allocates an empty value, calls
// Decode on the body bytes, then renders via encoding/json (the plugin emits
// snake_case json tags on each field).
func GenerateProtoRegistry(out io.Writer, input *Input) {
	d := input
	writer := &Writer{W: out}
	writer.Printf("// Code generated by ksdk/access/generator. DO NOT EDIT.\n\n")
	writer.Printf("package access\n\n")
	writer.Printf("import (\n")
	writer.Indented(func(w *Writer) {
		w.Printf("\"fmt\"\n")
	})
	writer.Printf(")\n\n")
	writer.Printf("// DTO is the minimal interface the AdminResponse receive path needs:\n")
	writer.Printf("// proto Decode + encoding/json relies on the value being a plain Go struct.\n")
	writer.Printf("type DTO interface {\n")
	writer.Printf("    Decode(data []byte) error\n")
	writer.Printf("    Append(buf []byte) ([]byte, error)\n")
	writer.Printf("}\n\n")

	var names []string
	for _, r := range d.Definition.Resources {
		for _, a := range r.Actions {
			names = append(names, fmt.Sprintf("Resource%sAction%sArgsDTO", toCamelCase(r.Name), toCamelCase(a.Name)))
			if a.Response != nil && a.Response.Use == nil {
				names = append(names, fmt.Sprintf("Resource%sAction%sResponseDTO", toCamelCase(r.Name), toCamelCase(a.Name)))
			}
		}
	}
	sort.Strings(names)

	writer.Printf("// dtoFactories maps a DTO short name to a factory that returns an\n")
	writer.Printf("// empty pointer to the corresponding pbaccess message type.\n")
	writer.Printf("var dtoFactories = map[string]func() DTO{\n")
	for _, n := range names {
		writer.Printf("    %q: func() DTO { return &%s{} },\n", n, n)
	}
	writer.Printf("}\n\n")

	writer.Printf("// NewDTOByName returns an empty pointer to the named DTO type, ready\n")
	writer.Printf("// to be filled via Decode. ok=false when name is not registered.\n")
	writer.Printf("func NewDTOByName(name string) (DTO, error) {\n")
	writer.Printf("    f, ok := dtoFactories[name]\n")
	writer.Printf("    if !ok { return nil, fmt.Errorf(\"unknown DTO type %%q\", name) }\n")
	writer.Printf("    return f(), nil\n")
	writer.Printf("}\n\n")

	writer.Printf("// DTONames returns the sorted list of registered DTO type names\n")
	writer.Printf("// (useful for diagnostics / completion).\n")
	writer.Printf("func DTONames() []string {\n")
	writer.Printf("    names := make([]string, 0, len(dtoFactories))\n")
	writer.Printf("    for k := range dtoFactories { names = append(names, k) }\n")
	writer.Printf("    return names\n")
	writer.Printf("}\n")
}
