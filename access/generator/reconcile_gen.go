package generator

import (
	"bytes"
	"fmt"
	"path/filepath"
	"strings"
)

// ReconcileFile is one generated reconcile-controller Go file.
type ReconcileFile struct {
	Path    string
	Content string
}

// GenerateReconcile emits, for every declarative resource carrying a reconcile
// spec, a controller into the reconcile package: {Resource}(ctx, store, broker,
// logger) that pushes the desired set to every dataplane node of the spec's
// dp_type — on a desired-state change (store.OnChange) and when a node connects
// (broker.OnConnect) — via the southbound service RPC. Idempotent: the full
// desired set is re-pushed each time. This is the generated wiring; the desired
// store stays hand-written (service/<r>), mirroring the gate/business split.
func GenerateReconcile(input *Input) []ReconcileFile {
	var files []ReconcileFile
	for i := range input.Definition.Resources {
		r := &input.Definition.Resources[i]
		if r.Schema == nil || r.Schema.Reconcile == nil || r.Schema.Reconcile.Custom {
			continue // Custom: the loop is hand-written in reconcile/<r>.go
		}
		var buf bytes.Buffer
		emitReconcile(&Writer{W: &buf}, r)
		files = append(files, ReconcileFile{
			Path:    filepath.Join("reconcile", r.Name+"_gen.go"),
			Content: buf.String(),
		})
	}
	return files
}

func emitReconcile(w *Writer, r *ResourceTemplate) {
	svc := toCamelCase(r.Name) // Vip
	rec := r.Schema.Reconcile
	reqType := fmt.Sprintf("pb.%s%sRequest", rec.Service, rec.Method)
	reqField := toCamelCase(rec.RequestField)
	// Multi-field: the desired element is the object DTO and each request field is
	// copied from a schema field; single-field: the element is the scalar key.
	multiField := len(rec.RequestFields) > 0
	// PerNode also makes the desired element the object DTO (so the node selector +
	// value travel together) and needs the access pkg for it.
	elemType := goTypeOf(keyField(r.Schema).Type) // desired element Go type (e.g. string)
	if multiField || rec.PerNode {
		elemType = "*pbaccess.Resource" + svc + "ActionGetResponseDTO"
	}
	keyCamel := toCamelCase(r.Schema.Key)
	keyType := goTypeOf(keyField(r.Schema).Type) // scalar key type (for the prune set)

	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package reconcile\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "log/slog")
		w.Printf("%q\n", "time")
		w.Printf("\n")
		w.Printf("%q\n", "github.com/on-keyday/kscale/dpbroker")
		w.Printf("%q\n", "github.com/on-keyday/kscale/peer")
		pkg := "github.com/on-keyday/kscale/protobuf/proto"
		w.Printf("pb %q\n", pkg)
		if multiField || rec.PerNode {
			w.Printf("pbaccess %q\n", "github.com/on-keyday/kscale/protobuf/proto/access")
		}
		if rec.Prune != nil {
			w.Printf("%q\n", "github.com/on-keyday/kscale/protobuf/wkt")
		}
		if rec.StatusObservedFrom != "" {
			w.Printf("pbstat %q\n", "github.com/on-keyday/kscale/protobuf/proto/stat")
		}
		w.Printf("%q\n", "github.com/on-keyday/kscale/rpc")
	})
	w.Printf(")\n\n")

	w.Printf("// %sDesired is the desired-state source the %s controller reconciles.\n", svc, svc)
	w.Printf("type %sDesired interface {\n", svc)
	w.Indented(func(w *Writer) {
		w.Printf("Desired() []%s\n", elemType)
		w.Printf("OnChange(func())\n")
	})
	w.Printf("}\n\n")

	if rec.PerNode {
		emitPerNodeController(w, r, svc, reqType, reqField, elemType)
		if rec.StatusObservedFrom != "" {
			emitStatusObserver(w, svc, rec.StatusObservedFrom)
		}
		return
	}

	w.Printf("// %s wires the reconcile loop: push the desired %s set to every %q\n", svc, r.Name, rec.DpType)
	w.Printf("// dataplane node via %s.%s, on desired change and on node connect.\n", rec.Service, rec.Method)
	w.Printf("func %s(ctx context.Context, store %sDesired, broker *dpbroker.Broker, status *Status, logger *slog.Logger) {\n", svc, svc)
	w.Indented(func(w *Writer) {
		w.Printf("push := func(p *peer.Peer) {\n")
		w.Indented(func(w *Writer) {
			w.Printf("c := pb.New%sClient(rpc.NewTrsfStreamSource(p.Streams(), logger))\n", rec.Service)
			itemExpr := "item"
			if rec.RequestBytes {
				itemExpr = "[]byte(item)"
			}
			reqArgs := fmt.Sprintf("%s: %s", reqField, itemExpr)
			itemLog := "item"
			if multiField {
				var parts []string
				for _, fm := range rec.RequestFields {
					parts = append(parts, fmt.Sprintf("%s: item.%s", toCamelCase(fm.To), toCamelCase(fm.From)))
				}
				reqArgs = strings.Join(parts, ", ")
				itemLog = "item." + keyCamel
			}
			w.Printf("var pushErr error\n")
			w.Printf("for _, item := range store.Desired() {\n")
			w.Indented(func(w *Writer) {
				w.Printf("if _, err := c.%s(ctx, &%s{%s}); err != nil {\n", rec.Method, reqType, reqArgs)
				w.Indented(func(w *Writer) {
					w.Printf("logger.Error(%q, \"item\", %s, \"error\", err)\n", "reconcile "+r.Name+": "+rec.Method+" failed", itemLog)
					w.Printf("pushErr = err\n")
				})
				w.Printf("}\n")
			})
			w.Printf("}\n")
			if rec.Prune != nil {
				emitPrune(w, r, keyType)
			}
			w.Printf("status.Record(%q, p.CommonName(), time.Now(), pushErr)\n", r.Name)
		})
		w.Printf("}\n")
		w.Printf("store.OnChange(func() {\n")
		w.Indented(func(w *Writer) {
			w.Printf("for _, p := range broker.List(%q) {\n", rec.DpType)
			w.Indented(func(w *Writer) { w.Printf("push(p)\n") })
			w.Printf("}\n")
		})
		w.Printf("})\n")
		w.Printf("broker.OnConnect(func(dpType string, p *peer.Peer) {\n")
		w.Indented(func(w *Writer) {
			w.Printf("if dpbroker.Matches(%q, dpType) {\n", rec.DpType)
			w.Indented(func(w *Writer) { w.Printf("push(p) // converge the new node to current desired state\n") })
			w.Printf("}\n")
		})
		w.Printf("})\n")
	})
	w.Printf("}\n")

	if rec.StatusObservedFrom != "" {
		emitStatusObserver(w, svc, rec.StatusObservedFrom)
	}
}

// emitPerNodeController generates a node-targeted reconcile (rec.PerNode): each
// desired item is the object DTO carrying a node selector (rec.NodeField) + a value
// (rec.RequestField); the value is pushed to ONLY the resolved node, on desired
// change and on that node's connect — so per-node state like the XDP interface each
// node binds is expressed, which a global broadcast set cannot.
func emitPerNodeController(w *Writer, r *ResourceTemplate, svc, reqType, reqField, elemType string) {
	rec := r.Schema.Reconcile
	nodeCamel := toCamelCase(rec.NodeField)
	valExpr := "best." + reqField
	if rec.RequestBytes {
		valExpr = "[]byte(best." + reqField + ")"
	}
	// Request args: single-field (reqField <- valExpr), or multi-field (each request
	// field <- best.<from>) when rec.RequestFields is set — mirrors the broadcast
	// emitter but reads the most-specific item (best). Multi-field values can be
	// sensitive (e.g. a router password), so those are NOT echoed into the error log.
	reqArgs := fmt.Sprintf("%s: %s", reqField, valExpr)
	logExtra := fmt.Sprintf("\"item\", %s, ", valExpr)
	if len(rec.RequestFields) > 0 {
		var parts []string
		for _, fm := range rec.RequestFields {
			parts = append(parts, fmt.Sprintf("%s: best.%s", toCamelCase(fm.To), toCamelCase(fm.From)))
		}
		reqArgs = strings.Join(parts, ", ")
		logExtra = ""
	}
	w.Printf("// %s wires the per-node reconcile loop: each desired item targets nodes via a\n", svc)
	w.Printf("// selector (%s: a node, a \"<dp_type>/*\" group, or \"*\"). Each node gets the\n", rec.NodeField)
	w.Printf("// value of its MOST SPECIFIC matching selector (node > group > *) via %s.%s,\n", rec.Service, rec.Method)
	w.Printf("// on desired change and on node connect.\n")
	w.Printf("func %s(ctx context.Context, store %sDesired, broker *dpbroker.Broker, status *Status, logger *slog.Logger) {\n", svc, svc)
	w.Indented(func(w *Writer) {
		w.Printf("apply := func(dpType string, p *peer.Peer) {\n")
		w.Indented(func(w *Writer) {
			w.Printf("if !dpbroker.Matches(%q, dpType) {\n", rec.DpType)
			w.Indented(func(w *Writer) { w.Printf("return\n") })
			w.Printf("}\n")
			w.Printf("// most-specific matching selector wins (node > group > *).\n")
			w.Printf("var best %s\n", elemType)
			w.Printf("bestSpec := 0\n")
			w.Printf("for _, item := range store.Desired() {\n")
			w.Indented(func(w *Writer) {
				w.Printf("if spec := broker.MatchSpecificity(item.%s, dpType, p); spec > bestSpec {\n", nodeCamel)
				w.Indented(func(w *Writer) { w.Printf("bestSpec, best = spec, item\n") })
				w.Printf("}\n")
			})
			w.Printf("}\n")
			w.Printf("if best == nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return\n") })
			w.Printf("}\n")
			w.Printf("c := pb.New%sClient(rpc.NewTrsfStreamSource(p.Streams(), logger))\n", rec.Service)
			w.Printf("_, err := c.%s(ctx, &%s{%s})\n", rec.Method, reqType, reqArgs)
			w.Printf("status.Record(%q, p.CommonName(), time.Now(), err)\n", r.Name)
			w.Printf("if err != nil {\n")
			w.Indented(func(w *Writer) {
				w.Printf("logger.Error(%q, \"node\", best.%s, %s\"error\", err)\n", "reconcile "+r.Name+": "+rec.Method+" failed", nodeCamel, logExtra)
			})
			w.Printf("}\n")
		})
		w.Printf("}\n")
		w.Printf("store.OnChange(func() { broker.ForEachNode(apply) })\n")
		w.Printf("broker.OnConnect(apply)\n")
	})
	w.Printf("}\n")
}

// emitPrune generates the deletion half of a multi-field reconcile (inside push,
// after the desired set is applied): build the desired-key set, list what is
// actually on the node (rec.Prune.ListMethod), and remove (RemoveMethod) anything
// whose key is no longer desired.
func emitPrune(w *Writer, r *ResourceTemplate, keyType string) {
	rec := r.Schema.Reconcile
	p := rec.Prune
	keyCamel := toCamelCase(r.Schema.Key)
	listFieldCamel := toCamelCase(p.ListField)
	itemKeyCamel := toCamelCase(p.ItemKey)
	removeReq := fmt.Sprintf("pb.%s%sRequest", rec.Service, p.RemoveMethod)
	removeFieldCamel := toCamelCase(p.RemoveField)
	w.Printf("// prune: remove anything on the node no longer in the desired set.\n")
	w.Printf("desired := map[%s]bool{}\n", keyType)
	w.Printf("for _, item := range store.Desired() {\n")
	w.Indented(func(w *Writer) { w.Printf("desired[item.%s] = true\n", keyCamel) })
	w.Printf("}\n")
	w.Printf("if resp, err := c.%s(ctx, &wkt.Empty{}); err == nil {\n", p.ListMethod)
	w.Indented(func(w *Writer) {
		w.Printf("for _, actual := range resp.%s {\n", listFieldCamel)
		w.Indented(func(w *Writer) {
			w.Printf("if !desired[actual.%s] {\n", itemKeyCamel)
			w.Indented(func(w *Writer) {
				w.Printf("if _, err := c.%s(ctx, &%s{%s: actual.%s}); err != nil {\n", p.RemoveMethod, removeReq, removeFieldCamel, itemKeyCamel)
				w.Indented(func(w *Writer) {
					w.Printf("logger.Error(%q, \"key\", actual.%s, \"error\", err)\n", "reconcile "+r.Name+": "+p.RemoveMethod+" failed", itemKeyCamel)
				})
				w.Printf("}\n")
			})
			w.Printf("}\n")
		})
		w.Printf("}\n")
	})
	w.Printf("}\n")
}

// emitStatusObserver generates {Svc}Observer: per desired item, the nodes whose
// latest reported pbstat.Stats list it at the dotted path (a StringList leaf).
// Implements vip.Observer (structurally) — the resource's observed status.
func emitStatusObserver(w *Writer, svc, path string) {
	segs := strings.Split(path, ".")
	access := "s"
	var nilChecks []string
	for _, seg := range segs {
		access += "." + seg
		nilChecks = append(nilChecks, access+" == nil")
	}

	w.Printf("\n")
	w.Printf("// %sStatSource is the per-node stat snapshot the observer reads.\n", svc)
	w.Printf("type %sStatSource interface {\n", svc)
	w.Indented(func(w *Writer) { w.Printf("Get(commonName string) *pbstat.StatBatch\n") })
	w.Printf("}\n\n")

	w.Printf("// %sObserver reports the observed status of a %s: the nodes whose latest\n", svc, svc)
	w.Printf("// reported stats list it at %s.\n", path)
	w.Printf("type %sObserver struct {\n", svc)
	w.Indented(func(w *Writer) {
		w.Printf("Cache  %sStatSource\n", svc)
		w.Printf("Broker *dpbroker.Broker\n")
	})
	w.Printf("}\n\n")

	w.Printf("func New%sObserver(cache %sStatSource, broker *dpbroker.Broker) *%sObserver {\n", svc, svc, svc)
	w.Indented(func(w *Writer) { w.Printf("return &%sObserver{Cache: cache, Broker: broker}\n", svc) })
	w.Printf("}\n\n")

	w.Printf("// AppliedNodes returns the nodes whose reported state includes item.\n")
	w.Printf("func (o *%sObserver) AppliedNodes(item string) []string {\n", svc)
	w.Indented(func(w *Writer) {
		w.Printf("var nodes []string\n")
		w.Printf("for _, ni := range o.Broker.Nodes() {\n")
		w.Indented(func(w *Writer) {
			w.Printf("for _, s := range o.Cache.Get(ni.CommonName).Stats {\n")
			w.Indented(func(w *Writer) {
				w.Printf("if %s {\n", strings.Join(nilChecks, " || "))
				w.Indented(func(w *Writer) { w.Printf("continue\n") })
				w.Printf("}\n")
				w.Printf("for _, v := range %s.Items {\n", access)
				w.Indented(func(w *Writer) {
					w.Printf("if v == item {\n")
					w.Indented(func(w *Writer) { w.Printf("nodes = append(nodes, ni.CommonName)\n") })
					w.Printf("}\n")
				})
				w.Printf("}\n")
			})
			w.Printf("}\n")
		})
		w.Printf("}\n")
		w.Printf("return nodes\n")
	})
	w.Printf("}\n")

	// ObservedSets: each node's full reported set at the path — the actual state,
	// for drift detection (reconcile.WatchDrift) against the desired set.
	w.Printf("\n")
	w.Printf("// ObservedSets returns each connected node's reported items at %s\n", path)
	w.Printf("// (actual state, for drift detection against desired).\n")
	w.Printf("func (o *%sObserver) ObservedSets() map[string][]string {\n", svc)
	w.Indented(func(w *Writer) {
		w.Printf("out := map[string][]string{}\n")
		w.Printf("for _, ni := range o.Broker.Nodes() {\n")
		w.Indented(func(w *Writer) {
			w.Printf("for _, s := range o.Cache.Get(ni.CommonName).Stats {\n")
			w.Indented(func(w *Writer) {
				w.Printf("if %s {\n", strings.Join(nilChecks, " || "))
				w.Indented(func(w *Writer) { w.Printf("continue\n") })
				w.Printf("}\n")
				w.Printf("out[ni.CommonName] = append(out[ni.CommonName], %s.Items...)\n", access)
			})
			w.Printf("}\n")
		})
		w.Printf("}\n")
		w.Printf("return out\n")
	})
	w.Printf("}\n")
}

// goTypeOf maps a yaml field type to the Go type the desired set is held as.
func goTypeOf(yamlType string) string {
	switch yamlType {
	case "string", "uint32", "uint64", "bool":
		return yamlType
	default:
		return "string"
	}
}
