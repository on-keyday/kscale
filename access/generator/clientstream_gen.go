package generator

import (
	"bytes"
	"fmt"
	"path/filepath"
)

// GenerateClientStream emits client/stream_gen.go: StreamResource, a metadata-driven
// router for SERVER-STREAMING actions. Unlike DispatchResource (which prints stream
// items to stdout), it invokes sink(jsonItem) per element until io.EOF — so a
// non-CLI client (the admin TUI) can render a live stream without owning stdout.
func GenerateClientStream(input *Input) ClientDispatchFile {
	type sact struct {
		cmds    []string
		method  string
		argsDTO string
		args    []ActionArg
	}
	type sres struct {
		rcmd string
		svc  string
		acts []sact
	}
	var all []sres
	needTime, needStrconv := false, false
	for i := range input.Definition.Resources {
		r := &input.Definition.Resources[i]
		if !r.generatesGate() {
			continue
		}
		svc := toCamelCase(r.Name)
		var acts []sact
		for _, a := range r.rpcActions() {
			if !a.isStreamingResponse() {
				continue
			}
			acts = append(acts, sact{
				cmds:    commandNames(&a),
				method:  toCamelCase(a.Name),
				argsDTO: fmt.Sprintf("pbaccess.Resource%sAction%sArgsDTO", svc, toCamelCase(a.Name)),
				args:    a.Args,
			})
			for _, arg := range a.Args {
				if isDurationArg(arg.Type) {
					needTime = true
				}
				if isIntegerArg(arg.Type) {
					needStrconv = true
				}
			}
		}
		if len(acts) > 0 {
			all = append(all, sres{rcmd: primaryCommandName(r), svc: svc, acts: acts})
		}
	}

	var buf bytes.Buffer
	w := &Writer{W: &buf}
	w.Printf("// Code generated by kscale/access/generator. DO NOT EDIT.\n")
	w.Printf("package client\n\n")
	w.Printf("import (\n")
	w.Indented(func(w *Writer) {
		w.Printf("%q\n", "context")
		w.Printf("%q\n", "encoding/json")
		w.Printf("%q\n", "errors")
		w.Printf("%q\n", "fmt")
		w.Printf("%q\n", "io")
		if needStrconv {
			w.Printf("%q\n", "strconv")
		}
		if needTime {
			w.Printf("%q\n", "time")
		}
		w.Printf("\n")
		w.Printf("pb %q\n", "github.com/on-keyday/kscale/protobuf/proto")
		w.Printf("pbaccess %q\n", "github.com/on-keyday/kscale/protobuf/proto/access")
		w.Printf("%q\n", "github.com/on-keyday/kscale/protobuf/wire")
	})
	w.Printf(")\n\n")

	w.Printf("// StreamResource invokes a server-streaming action (resource/action by\n")
	w.Printf("// command_name), calling sink(jsonItem) for each element until the stream\n")
	w.Printf("// ends; returns an error for a non-streaming action. The caller controls the\n")
	w.Printf("// stream lifetime via ctx (cancel to stop).\n")
	w.Printf("func StreamResource(ctx context.Context, src *wire.StreamSource, resource, action string, args map[string]string, sink func(string) error) error {\n")
	w.Indented(func(w *Writer) {
		w.Printf("switch resource {\n")
		for _, rs := range all {
			w.Printf("case %q:\n", rs.rcmd)
			w.Indented(func(w *Writer) {
				w.Printf("c := pb.New%sServiceClient(src)\n", rs.svc)
				w.Printf("switch action {\n")
				for _, a := range rs.acts {
					for _, cmd := range a.cmds {
						w.Printf("case %q:\n", cmd)
					}
					w.Indented(func(w *Writer) {
						w.Printf("dto := &%s{}\n", a.argsDTO)
						for i := range a.args {
							emitStreamArgBind(w, &a.args[i])
						}
						w.Printf("stream, err := c.%s(ctx, dto)\n", a.method)
						w.Printf("if err != nil {\n")
						w.Indented(func(w *Writer) { w.Printf("return err\n") })
						w.Printf("}\n")
						w.Printf("for {\n")
						w.Indented(func(w *Writer) {
							w.Printf("item, err := stream.Recv(ctx)\n")
							w.Printf("if errors.Is(err, io.EOF) {\n")
							w.Indented(func(w *Writer) { w.Printf("return nil\n") })
							w.Printf("}\n")
							w.Printf("if err != nil {\n")
							w.Indented(func(w *Writer) { w.Printf("return err\n") })
							w.Printf("}\n")
							w.Printf("b, err := json.MarshalIndent(item, \"\", \"  \")\n")
							w.Printf("if err != nil {\n")
							w.Indented(func(w *Writer) { w.Printf("return err\n") })
							w.Printf("}\n")
							w.Printf("if err := sink(string(b)); err != nil {\n")
							w.Indented(func(w *Writer) { w.Printf("return err\n") })
							w.Printf("}\n")
						})
						w.Printf("}\n")
					})
				}
				w.Printf("}\n")
			})
		}
		w.Printf("}\n")
		w.Printf("return fmt.Errorf(%q, resource, action)\n", "%s %s is not a streaming action")
	})
	w.Printf("}\n")
	return ClientDispatchFile{Path: filepath.Join("client", "stream_gen.go"), Content: buf.String()}
}

// emitStreamArgBind binds one action arg into dto for the stream router (single
// error return, unlike emitClientDispatchCase which returns (string, error)).
func emitStreamArgBind(w *Writer, arg *ActionArg) {
	field := toCamelCase(arg.Name)
	switch {
	case isStringArg(arg.Type):
		if arg.Default != nil {
			w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
			w.Indented(func(w *Writer) { w.Printf("dto.%s = v\n", field) })
			w.Printf("} else {\n")
			w.Indented(func(w *Writer) { w.Printf("dto.%s = %q\n", field, *arg.Default) })
			w.Printf("}\n")
		} else {
			w.Printf("dto.%s = args[%q]\n", field, arg.Name)
		}
	case isDurationArg(arg.Type):
		w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
		w.Indented(func(w *Writer) {
			w.Printf("d, err := time.ParseDuration(v)\n")
			w.Printf("if err != nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w") })
			w.Printf("}\n")
			w.Printf("dto.%s = d\n", field)
		})
		w.Printf("}\n")
	case isIntegerArg(arg.Type):
		w.Printf("if v, ok := args[%q]; ok {\n", arg.Name)
		w.Indented(func(w *Writer) {
			w.Printf("n, err := strconv.ParseInt(v, 10, 64)\n")
			w.Printf("if err != nil {\n")
			w.Indented(func(w *Writer) { w.Printf("return fmt.Errorf(%q, err)\n", "arg "+arg.Name+": %w") })
			w.Printf("}\n")
			w.Printf("dto.%s = %s(n)\n", field, dtoIntGoType(arg.Type))
		})
		w.Printf("}\n")
	}
}
